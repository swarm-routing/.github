// The sweep (an org-bot task) acts on open Dependabot pull requests:
//
//   - here (Home), it commits Sync's template pins onto the pull request's
//     branch, so a Dependabot bump of .github/workflows/ moves templates/ in
//     the same pull request;
//   - in every other repository, on a pull request that edits org-managed
//     files (their first line is ManagedMarker), those edits are not the
//     repository's to make. When it edits nothing else, it is closed with a
//     comment: the pins reach the repository through org-bot's org-sync
//     refresh. When it also bumps the repository's own workflows, it is
//     asked to rebase (`@dependabot rebase`) once the default branch holds
//     the managed files exactly as the pull request would make them (the
//     refresh landed), so the rebased pull request touches only its own
//     files and passes `check / org-sync`; until then it waits.
//
// Each pull request is acted on once per head commit (a hidden marker in the
// comment), and at most MaxActions times a run.

const (
	// Org is the organization swept; Home is this repository.
	Org  = "swarm-routing"
	Home = Org + "/.github"
	// Bot is the author of the pull requests swept.
	Bot = "dependabot[bot]"
	// ManagedMarker begins every file org-sync renders from templates/.
	ManagedMarker = "# Managed by swarm-routing/.github tools/org-sync"
	// MaxActions bounds the commits, closes and comments of one run (golden rule 7).
	MaxActions = 50
	// maxFiles bounds the files read from one tree or pull request.
	maxFiles = 400
	maxPages = 20
)

var repoName = regexp.MustCompile(`^[A-Za-z0-9_.-]+$`)

// GitHub is the REST client: base URL, token, HTTP client.
type GitHub struct {
	API    string
	Token  string
	Client *http.Client
}

func (g GitHub) rest() github.Client {
	return github.Client{API: g.API, Token: g.Token, UserAgent: "swarm-routing-action-pins", HTTP: g.Client}
}

func (g GitHub) do(method, path string, body any, out any) error {
	data, err := g.rest().Do(method, path, body)
	if err != nil || out == nil {
		return err
	}
	if err := json.Unmarshal(data, out); err != nil {
		return fmt.Errorf("%s %s: %v", method, path, err)
	}
	return nil
}

type repo struct {
	Name          string `json:"name"`
	FullName      string `json:"full_name"`
	DefaultBranch string `json:"default_branch"`
	Archived      bool   `json:"archived"`
	Private       bool   `json:"private"`
}

type pull struct {
	Number int `json:"number"`
	User   struct {
		Login string `json:"login"`
	} `json:"user"`
	Head struct {
		Ref  string `json:"ref"`
		SHA  string `json:"sha"`
		Repo *struct {
			FullName string `json:"full_name"`
		} `json:"repo"`
	} `json:"head"`
}

func (g GitHub) repos(names []string) ([]repo, error) {
	if len(names) == 0 {
		all, err := github.List[repo](g.rest(), "orgs/"+Org+"/repos?type=all", maxPages)
		sort.Slice(all, func(i, j int) bool { return strings.ToLower(all[i].Name) < strings.ToLower(all[j].Name) })
		return all, err
	}
	var out []repo
	for _, n := range names {
		if !repoName.MatchString(n) {
			return nil, fmt.Errorf("%q is not a repository name", n)
		}
		var r repo
		if err := g.do("GET", "repos/"+Org+"/"+n, nil, &r); err != nil {
			return nil, err
		}
		out = append(out, r)
	}
	return out, nil
}

func (g GitHub) blob(full, sha string) (string, error) {
	var b struct {
		Content  string `json:"content"`
		Encoding string `json:"encoding"`
	}
	if err := g.do("GET", fmt.Sprintf("repos/%s/git/blobs/%s", full, sha), nil, &b); err != nil {
		return "", err
	}
	if b.Encoding != "base64" {
		return "", fmt.Errorf("blob %s of %s: encoding %q", sha, full, b.Encoding)
	}
	data, err := base64.StdEncoding.DecodeString(strings.ReplaceAll(b.Content, "\n", ""))
	return string(data), err
}

// marker is the hidden line that records an action on one head commit.
func marker(sha string) string { return "<!-- action-pins " + sha + " -->" }

func (g GitHub) acted(full string, n int, sha string) (bool, error) {
	type comment struct {
		Body string `json:"body"`
	}
	cs, err := github.List[comment](g.rest(), fmt.Sprintf("repos/%s/issues/%d/comments?sort=created", full, n), maxPages)
	if err != nil {
		return false, err
	}
	for _, c := range cs {
		if strings.Contains(c.Body, marker(sha)) {
			return true, nil
		}
	}
	return false, nil
}

const footer = "\n\n---\n_Generated by org-bot's `action-pins` sweep (swarm-routing/.github#773)_"

// CloseText and RebaseText are the comments the sweep posts in a consumer.
const CloseText = "Every file this pull request changes is managed by org-sync (its first line is `" + ManagedMarker +
	"`), so its pins are not this repository's to move: Dependabot bumps them in swarm-routing/.github, where " +
	"`action-pins` carries each bump into `templates/`, and org-bot's org-sync refresh pull request brings them here. " +
	"Closing it as superseded. Bumps of this repository's own workflows still come from Dependabot here."

const RebaseText = "@dependabot rebase\n\nThis pull request also changes files org-sync manages (their first line is `" + ManagedMarker +
	"`). The default branch now holds them as this pull request would make them (org-bot's org-sync refresh landed), " +
	"so a rebase leaves only this repository's own workflows and passes `check / org-sync`."

// Result counts what a run did (or, dry, would do).
type Result struct{ Committed, Closed, Rebased, Waiting, Failed int }

type sweeper struct {
	g      GitHub
	dry    bool
	out    io.Writer
	budget int
	res    Result
}

func (s *sweeper) spend(label string, n int, what string) bool {
	if s.budget <= 0 {
		fmt.Fprintf(s.out, "%s#%d: %s; deferred (%d actions a run)\n", label, n, what, MaxActions)
		return false
	}
	s.budget--
	return true
}

// home commits the template pins onto one Dependabot pull request here.
func (s *sweeper) home(r repo, p pull, label string) error {
	var tree struct {
		SHA       string `json:"sha"`
		Truncated bool   `json:"truncated"`
		Tree      []struct {
			Path string `json:"path"`
			Mode string `json:"mode"`
			Type string `json:"type"`
			SHA  string `json:"sha"`
		} `json:"tree"`
	}
	if err := s.g.do("GET", fmt.Sprintf("repos/%s/git/trees/%s?recursive=1", r.FullName, p.Head.SHA), nil, &tree); err != nil {
		return err
	}
	if tree.Truncated {
		return fmt.Errorf("the tree of %s is truncated", p.Head.SHA)
	}
	files, modes := map[string]string{}, map[string]string{}
	for _, e := range tree.Tree {
		if e.Type != "blob" || (!Source(e.Path) && !Template(e.Path)) {
			continue
		}
		if len(files) >= maxFiles {
			return fmt.Errorf("more than %d workflow and template files", maxFiles)
		}
		text, err := s.g.blob(r.FullName, e.SHA)
		if err != nil {
			return err
		}
		files[e.Path], modes[e.Path] = text, e.Mode
	}
	changed, found, err := Sync(files)
	if err != nil {
		return err
	}
	for _, f := range found {
		fmt.Fprintf(s.out, "%s#%d: %s\n", label, p.Number, f)
	}
	if len(changed) == 0 {
		fmt.Fprintf(s.out, "%s#%d: templates at the workflows' pins\n", label, p.Number)
		return nil
	}
	paths := sorted(changed)
	what := fmt.Sprintf("move %d template files to the workflows' pins (%s)", len(paths), strings.Join(paths, ", "))
	if !s.spend(label, p.Number, what) {
		return nil
	}
	if s.dry {
		fmt.Fprintf(s.out, "%s#%d: dry run: would %s\n", label, p.Number, what)
		s.res.Committed++
		return nil
	}
	type entry struct {
		Path    string `json:"path"`
		Mode    string `json:"mode"`
		Type    string `json:"type"`
		Content string `json:"content"`
	}
	var entries []entry
	for _, path := range paths {
		entries = append(entries, entry{path, modes[path], "blob", changed[path]})
	}
	var nt, nc struct {
		SHA string `json:"sha"`
	}
	if err := s.g.do("POST", "repos/"+r.FullName+"/git/trees", map[string]any{"base_tree": tree.SHA, "tree": entries}, &nt); err != nil {
		return err
	}
	msg := "chore(deps): move the template pins to the workflows' pins\n\n" +
		"action-pins (swarm-routing/.github#773): every third-party `uses:` in templates/\n" +
		"names the commit and version .github/workflows/ uses for the same action.\n\n" +
		strings.Join(paths, "\n") + "\n"
	if err := s.g.do("POST", "repos/"+r.FullName+"/git/commits",
		map[string]any{"message": msg, "tree": nt.SHA, "parents": []string{p.Head.SHA}}, &nc); err != nil {
		return err
	}
	if err := s.g.do("PATCH", "repos/"+r.FullName+"/git/refs/heads/"+refPath(p.Head.Ref),
		map[string]any{"sha": nc.SHA, "force": false}, nil); err != nil {
		return err
	}
	fmt.Fprintf(s.out, "%s#%d: committed %s: %s\n", label, p.Number, nc.SHA[:min(12, len(nc.SHA))], what)
	s.res.Committed++
	return nil
}

// consumer closes, or asks to rebase, one Dependabot pull request that edits org-managed files.
func (s *sweeper) consumer(r repo, p pull, label string) error {
	type file struct {
		Filename string `json:"filename"`
		Status   string `json:"status"`
		SHA      string `json:"sha"`
	}
	fs, err := github.List[file](s.g.rest(), fmt.Sprintf("repos/%s/pulls/%d/files?", r.FullName, p.Number), maxFiles/100)
	if err != nil {
		return err
	}
	managed := map[string]string{} // path -> text at the head
	ownFiles := 0
	for _, f := range fs {
		if f.Status == "removed" || f.SHA == "" {
			ownFiles++
			continue
		}
		text, err := s.g.blob(r.FullName, f.SHA)
		if err != nil {
			return err
		}
		if strings.HasPrefix(text, ManagedMarker) {
			managed[f.Filename] = text
		} else {
			ownFiles++
		}
	}
	if len(managed) == 0 {
		return nil
	}
	done, err := s.g.acted(r.FullName, p.Number, p.Head.SHA)
	if err != nil {
		return err
	}
	if done {
		fmt.Fprintf(s.out, "%s#%d: already handled at %s\n", label, p.Number, p.Head.SHA[:min(12, len(p.Head.SHA))])
		return nil
	}
	if ownFiles == 0 {
		what := fmt.Sprintf("close: edits only org-managed files (%d)", len(managed))
		if !s.spend(label, p.Number, what) {
			return nil
		}
		if s.dry {
			fmt.Fprintf(s.out, "%s#%d: dry run: would %s\n", label, p.Number, what)
			s.res.Closed++
			return nil
		}
		if err := s.comment(r, p, CloseText); err != nil {
			return err
		}
		if err := s.g.do("PATCH", fmt.Sprintf("repos/%s/pulls/%d", r.FullName, p.Number), map[string]any{"state": "closed"}, nil); err != nil {
			return err
		}
		fmt.Fprintf(s.out, "%s#%d: closed: edits only org-managed files (%d)\n", label, p.Number, len(managed))
		s.res.Closed++
		return nil
	}
	for _, path := range sorted(managed) {
		var c struct {
			Content  string `json:"content"`
			Encoding string `json:"encoding"`
		}
		err := s.g.do("GET", fmt.Sprintf("repos/%s/contents/%s?ref=%s", r.FullName, escPath(path), url.QueryEscape(r.DefaultBranch)), nil, &c)
		if err != nil && github.Status(err) != http.StatusNotFound {
			return err
		}
		data, _ := base64.StdEncoding.DecodeString(strings.ReplaceAll(c.Content, "\n", ""))
		if err != nil || c.Encoding != "base64" || string(data) != managed[path] {
			fmt.Fprintf(s.out, "%s#%d: waiting: %s on %s is not yet the pull request's (org-sync refresh pending)\n",
				label, p.Number, path, r.DefaultBranch)
			s.res.Waiting++
			return nil
		}
	}
	what := fmt.Sprintf("ask to rebase: %s holds its %d org-managed files", r.DefaultBranch, len(managed))
	if !s.spend(label, p.Number, what) {
		return nil
	}
	if s.dry {
		fmt.Fprintf(s.out, "%s#%d: dry run: would %s\n", label, p.Number, what)
		s.res.Rebased++
		return nil
	}
	if err := s.comment(r, p, RebaseText); err != nil {
		return err
	}
	fmt.Fprintf(s.out, "%s#%d: asked to rebase: %s holds its %d org-managed files\n", label, p.Number, r.DefaultBranch, len(managed))
	s.res.Rebased++
	return nil
}

func (s *sweeper) comment(r repo, p pull, text string) error {
	body := text + "\n\n" + marker(p.Head.SHA) + footer
	return s.g.do("POST", fmt.Sprintf("repos/%s/issues/%d/comments", r.FullName, p.Number), map[string]any{"body": body}, nil)
}

func refPath(name string) string { return escPath(name) }

func escPath(p string) string {
	parts := strings.Split(p, "/")
	for i, x := range parts {
		parts[i] = url.PathEscape(x)
	}
	return strings.Join(parts, "/")
}

// Sweep runs over every unarchived org repository (or the named ones); it
// tries them all and returns an error when any failed.
func Sweep(g GitHub, names []string, dry bool, out io.Writer) (Result, error) {
	s := &sweeper{g: g, dry: dry, out: out, budget: MaxActions}
	rs, err := g.repos(names)
	if err != nil {
		return s.res, err
	}
	var mask repomask.Masker // a public workflow log never names a private repository
	failed := 0
	for _, r := range rs {
		label := mask.Repo(r.Name, r.Private, r.FullName, r.Name)
		if r.Archived || r.FullName != Org+"/"+r.Name || !repoName.MatchString(r.Name) {
			continue
		}
		pulls, err := github.List[pull](g.rest(), "repos/"+r.FullName+"/pulls?state=open", maxPages)
		if err != nil {
			fmt.Fprintf(out, "%s: error: %v\n", label, mask.Error(err))
			failed++
			continue
		}
		for _, p := range pulls {
			if p.User.Login != Bot || p.Head.Repo == nil || p.Head.Repo.FullName != r.FullName {
				continue
			}
			if r.FullName == Home {
				err = s.home(r, p, label)
			} else {
				err = s.consumer(r, p, label)
			}
			if err != nil {
				fmt.Fprintf(out, "%s#%d: error: %v\n", label, p.Number, mask.Error(err))
				s.res.Failed++
			}
		}
	}
	verb := ""
	if dry {
		verb = "dry run: "
	}
	fmt.Fprintf(out, "action-pins: %s%d repositories; committed %d, closed %d, asked to rebase %d, waiting %d, failed %d\n",
		verb, len(rs), s.res.Committed, s.res.Closed, s.res.Rebased, s.res.Waiting, s.res.Failed+failed)
	if failed > 0 || s.res.Failed > 0 {
		return s.res, fmt.Errorf("%d repositories and %d pull requests failed", failed, s.res.Failed)
	}
	return s.res, nil
}

const usage = `usage: action-pins [--write] [DIR]           check (or write) the template pins of a checkout (default .)
       action-pins sweep [--dry-run] [--repos A,B]  act on the org's open Dependabot pull requests (GH_TOKEN)`

// Main is the command.
func Main(args []string, getenv func(string) string, client *http.Client, api string, stdout, stderr io.Writer) int {
	if len(args) > 0 && args[0] == "sweep" {
		dry := false
		var names []string
		for i := 1; i < len(args); i++ {
			switch a := args[i]; {
			case a == "--dry-run":
				dry = true
			case a == "--repos" && i+1 < len(args):
				for _, n := range strings.Split(args[i+1], ",") {
					if n = strings.TrimSpace(n); n != "" {
						names = append(names, n)
					}
				}
				i++
			default:
				fmt.Fprintln(stderr, usage)
				return 2
			}
		}
		token := getenv("GH_TOKEN")
		if token == "" && !dry {
			fmt.Fprintln(stdout, "action-pins: no GH_TOKEN: dry run")
			dry = true
		}
		if _, err := Sweep(GitHub{API: api, Token: token, Client: client}, names, dry, stdout); err != nil {
			fmt.Fprintln(stderr, "action-pins:", err)
			return 1
		}
		return 0
	}
	write, dir := false, "."
	for i, a := range args {
		switch {
		case a == "--write":
			write = true
		case a == "-h" || a == "--help":
			fmt.Fprintln(stdout, usage)
			return 0
		case !strings.HasPrefix(a, "-") && i == len(args)-1:
			dir = a
		default:
			fmt.Fprintln(stderr, usage)
			return 2
		}
	}
	return Local(dir, write, stdout)
}
