const (
	// Org is the organization watched.
	Org = "swarm-routing"
	// Label marks every ticket.
	Label = "security"
	// EscalateDays: a medium-or-higher alert open longer is past its SLA.
	EscalateDays = 45
	// CriticalDays: a critical alert open longer is past its SLA.
	CriticalDays = 14
	// ReportTitle is the weekly summary issue in swarm-routing/.github.
	ReportTitle = "[security] open alerts across the org"
	// Footer ends every issue and comment.
	Footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
	// maxPages bounds every listing: 100 items a page.
	maxPages = 10
)

var repoName = regexp.MustCompile(`^[A-Za-z0-9_.-]+$`)

// GitHub is the REST client: base URL, token, HTTP client.
type GitHub struct {
	API    string
	Token  string
	Client *http.Client
}

type apiError struct {
	status int
	msg    string
}

func (e *apiError) Error() string { return e.msg }

func (g GitHub) do(method, path string, body any) ([]byte, error) {
	data, _, err := g.doLink(method, path, body)
	return data, err
}

// linkNext is the next page's URL in a Link header (cursor or page based:
// the Dependabot listing refuses `page`).
var linkNext = regexp.MustCompile(`<([^>]+)>;\s*rel="next"`)

// doLink is do, also returning the next page's path from the Link header.
func (g GitHub) doLink(method, path string, body any) ([]byte, string, error) {
	var rd io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			return nil, "", err
		}
		rd = bytes.NewReader(b)
	}
	req, err := http.NewRequest(method, g.API+"/"+path, rd)
	if err != nil {
		return nil, "", err
	}
	req.Header.Set("Accept", "application/vnd.github+json")
	req.Header.Set("X-GitHub-Api-Version", "2022-11-28")
	req.Header.Set("User-Agent", "swarm-routing-security-alerts")
	if g.Token != "" {
		req.Header.Set("Authorization", "Bearer "+g.Token)
	}
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := g.Client.Do(req)
	if err != nil {
		msg := err.Error()
		if g.Token != "" {
			msg = strings.ReplaceAll(msg, g.Token, "[redacted]")
		}
		return nil, "", fmt.Errorf("%s %s: %s", method, path, msg)
	}
	defer resp.Body.Close()
	data, err := io.ReadAll(io.LimitReader(resp.Body, 8<<20))
	if err != nil {
		return nil, "", err
	}
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		msg := strings.TrimSpace(string(data))
		if len(msg) > 200 {
			msg = msg[:200]
		}
		return nil, "", &apiError{resp.StatusCode, fmt.Sprintf("%s %s: HTTP %d: %s", method, path, resp.StatusCode, msg)}
	}
	next := ""
	if m := linkNext.FindStringSubmatch(resp.Header.Get("Link")); m != nil {
		next = strings.TrimPrefix(m[1], g.API+"/")
	}
	return data, next, nil
}

func status(err error) int {
	var e *apiError
	if errors.As(err, &e) {
		return e.status
	}
	return 0
}

func list[T any](g GitHub, path string) ([]T, error) {
	var out []T
	next := path + "&per_page=100"
	for page := 1; page <= maxPages && next != ""; page++ {
		data, n, err := g.doLink("GET", next, nil)
		if err != nil {
			return nil, err
		}
		var got []T
		if err := json.Unmarshal(data, &got); err != nil {
			return nil, fmt.Errorf("GET %s: %v", path, err)
		}
		out = append(out, got...)
		next = n
	}
	return out, nil
}

// Kinds of alert, in the order they are read.
const (
	CodeScanning   = "code scanning"
	Dependabot     = "Dependabot"
	SecretScanning = "secret scanning"
)

var kindPath = map[string]string{
	CodeScanning:   "code-scanning/alerts",
	Dependabot:     "dependabot/alerts",
	SecretScanning: "secret-scanning/alerts",
}

// Alert is one open alert.
type Alert struct {
	Kind     string
	Number   int
	URL      string
	Created  time.Time
	Severity string // critical, high, medium, low ("" for a secret)
	Tool     string // the code-scanning tool
	What     string // the rule, the advisory or the secret type (data, quoted)
	// Security: Severity is a security severity (a Dependabot advisory's, or
	// a code-scanning rule's security_severity_level), not a rule's plain
	// error/warning/note or the medium default
	Security bool
}

// rawAlert is every listing's shape, read leniently.
type rawAlert struct {
	Number  int       `json:"number"`
	URL     string    `json:"html_url"`
	Created time.Time `json:"created_at"`
	Tool    struct {
		Name string `json:"name"`
	} `json:"tool"`
	Rule struct {
		ID          string `json:"id"`
		Description string `json:"description"`
		Severity    string `json:"severity"`
		SecSeverity string `json:"security_severity_level"`
	} `json:"rule"`
	Advisory struct {
		Summary  string `json:"summary"`
		Severity string `json:"severity"`
		GHSA     string `json:"ghsa_id"`
	} `json:"security_advisory"`
	Dependency struct {
		Package struct {
			Name string `json:"name"`
		} `json:"package"`
	} `json:"dependency"`
	SecretType string `json:"secret_type_display_name"`
}

func normSeverity(s string) string {
	switch strings.ToLower(s) {
	case "critical":
		return "critical"
	case "high", "error":
		return "high"
	case "medium", "moderate", "warning":
		return "medium"
	case "low", "note":
		return "low"
	}
	return ""
}

func (r rawAlert) alert(kind string) Alert {
	a := Alert{Kind: kind, Number: r.Number, URL: r.URL, Created: r.Created}
	switch kind {
	case CodeScanning:
		a.Tool = r.Tool.Name
		a.Severity = normSeverity(r.Rule.SecSeverity)
		a.Security = a.Severity != ""
		if a.Severity == "" {
			a.Severity = normSeverity(r.Rule.Severity)
		}
		if a.Severity == "" {
			a.Severity = "medium"
		}
		a.What = r.Rule.ID
		if r.Rule.Description != "" {
			a.What += ": " + r.Rule.Description
		}
	case Dependabot:
		a.Severity = normSeverity(r.Advisory.Severity)
		a.Security = a.Severity != ""
		if a.Severity == "" {
			a.Severity = "medium"
		}
		a.What = strings.TrimSpace(r.Dependency.Package.Name + " " + r.Advisory.GHSA + ": " + r.Advisory.Summary)
	case SecretScanning:
		a.What = r.SecretType
	}
	return a
}

// FromJSON reads one item of an alert listing, already decoded from JSON,
// as Sync reads it: the one reading of an alert's number, URL, age and
// severity for every tool (bestpractices' vulnerability criteria, #680).
func FromJSON(kind string, item any) (Alert, error) {
	b, err := json.Marshal(item)
	if err != nil {
		return Alert{}, err
	}
	var r rawAlert
	if err := json.Unmarshal(b, &r); err != nil {
		return Alert{}, fmt.Errorf("%s alert: %v", kind, err)
	}
	return r.alert(kind), nil
}

// Policy: a code-scanning finding about repository policy, not code.
func (a Alert) Policy() bool { return a.Kind == CodeScanning && strings.EqualFold(a.Tool, "Scorecard") }

// Age is how long the alert has been open.
func (a Alert) Age(now time.Time) time.Duration { return now.Sub(a.Created) }

// PastSLA: open longer than its severity allows.
func (a Alert) PastSLA(now time.Time) bool {
	switch a.Severity {
	case "critical":
		return a.Age(now) > CriticalDays*24*time.Hour
	case "high", "medium":
		return a.Age(now) > EscalateDays*24*time.Hour
	}
	return false
}

// Priority from the severity, P1 for a secret or past the SLA.
func (a Alert) Priority(now time.Time) string {
	if a.Kind == SecretScanning || a.PastSLA(now) {
		return "P1"
	}
	switch a.Severity {
	case "critical", "high":
		return "P1"
	case "medium":
		return "P2"
	}
	return "P3"
}

// clip quotes alert text: collapsed, clipped, no backticks, no @-mentions.
func clip(s string, n int) string {
	s = strings.Join(strings.Fields(s), " ")
	s = strings.NewReplacer("`", "'", "@", "(at)", "<", "‹", ">", "›").Replace(s)
	if len(s) > n {
		s = s[:n] + "..."
	}
	return s
}

// Marker is the hidden line that ties an issue to its alert.
func Marker(url string) string { return "<!-- security-alert: " + url + " -->" }

// namesURL: text names url followed by its end or a non-digit (#621).
func namesURL(text, url string) bool {
	for off := 0; ; {
		i := strings.Index(text[off:], url)
		if i < 0 {
			return false
		}
		end := off + i + len(url)
		if end == len(text) || text[end] < '0' || text[end] > '9' {
			return true
		}
		off += i + 1
	}
}

// Title of an alert's issue.
func Title(a Alert) string {
	what := a.What
	if i := strings.Index(what, ":"); i > 0 && a.Kind == CodeScanning {
		what = what[:i]
	}
	if what == "" {
		return fmt.Sprintf("[security] %s alert #%d", a.Kind, a.Number)
	}
	return fmt.Sprintf("[security] %s alert #%d: %s", a.Kind, a.Number, clip(what, 80))
}

// Body of an alert's issue.
func Body(a Alert, now time.Time) string {
	sev := a.Severity
	if sev == "" {
		sev = "a leaked secret"
	}
	days := int(a.Age(now).Hours() / 24)
	lines := []string{Marker(a.URL), "## Context", "",
		fmt.Sprintf("An open %s alert in this repository: %s", a.Kind, a.URL), "",
		"- Severity: " + sev,
		fmt.Sprintf("- Open since %s (%d days)", a.Created.UTC().Format("2006-01-02"), days)}
	if a.Tool != "" {
		lines = append(lines, "- Tool: "+clip(a.Tool, 40))
	}
	if a.What != "" {
		lines = append(lines, "- Finding: "+clip(a.What, 300))
	}
	if a.PastSLA(now) {
		lines = append(lines, "", fmt.Sprintf("**Past its SLA** (critical: %d days, medium or higher: %d days): this issue is P1, "+
			"and the OpenSSF Best Practices vulnerability answers are withdrawn until it closes.", CriticalDays, EscalateDays))
	}
	lines = append(lines, "", "## Who acts", "")
	var done string
	switch {
	case a.Kind == SecretScanning:
		lines = append(lines, "The maintainer rotates the secret: rotation needs the maintainer's accounts, and removing it "+
			"from the tree does not revoke it. No agent fixes a leaked secret.")
		done = "- [ ] The maintainer revokes the credential at its issuer, issues a new one where needed, and closes the alert as revoked."
	case a.Policy():
		lines = append(lines, "A repository policy finding: `security-autofix.yml` posts a proposal here (a settings-as-code "+
			"change through `[settings]` where one fixes it, else a dismissal with its reason). Dismissing the alert is the "+
			"maintainer's decision; an agent never dismisses an alert.")
		done = "- [ ] The policy changes and the alert closes, or the maintainer dismisses it with its reason."
	case a.Kind == Dependabot:
		lines = append(lines, "Dependabot opens the security update PR (security updates are on in every repository); "+
			"review and merge it through the usual checks.")
		done = "- [ ] The security update is merged and the alert closes."
	default:
		lines = append(lines, "`security-autofix.yml` (swarm-routing/.github#629) opens a fix PR: a reproducing test first, "+
			"then a minimal fix, through the required CI, the CodeRabbit review and the merge queue. Dismissing the alert "+
			"instead is the maintainer's decision.")
		done = "- [ ] The fix is merged and the alert closes, or the maintainer dismisses it with its reason."
	}
	lines = append(lines, "", "## Acceptance criteria", "", done, "",
		"This issue is kept by the hourly `security-alerts` task (swarm-routing/.github `cmd/security-alerts`): "+
			"updated in place, and closed when the alert is no longer open.")
	return strings.Join(lines, "\n") + Footer
}

// Labels of an alert's issue.
func Labels(a Alert, now time.Time) []string {
	return []string{Label, "bug", "ci", "model:sonnet-5.5", "priority:" + a.Priority(now)}
}

// Issue is a ticket as read.
type Issue struct {
	Number int    `json:"number"`
	Title  string `json:"title"`
	Body   string `json:"body"`
	State  string `json:"state"`
	Labels []struct {
		Name string `json:"name"`
	} `json:"labels"`
	PR any `json:"pull_request"`
}

func (i Issue) labelNames() []string {
	var out []string
	for _, l := range i.Labels {
		out = append(out, l.Name)
	}
	return out
}

// markerURL is the alert URL an issue's marker names, or "".
var markerRe = regexp.MustCompile(`<!-- security-alert: (\S+) -->`)

func markerURL(body string) string {
	if m := markerRe.FindStringSubmatch(body); m != nil {
		return m[1]
	}
	return ""
}

// mergeLabels keeps an issue's own labels, replaces its priority and adds
// the ticket's.
func mergeLabels(have, want []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, l := range have {
		if strings.HasPrefix(l, "priority:") || strings.HasPrefix(l, "model:") {
			continue
		}
		if !seen[l] {
			seen[l] = true
			out = append(out, l)
		}
	}
	for _, l := range want {
		if !seen[l] {
			seen[l] = true
			out = append(out, l)
		}
	}
	sort.Strings(out)
	return out
}

func sameSet(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	x := append([]string(nil), a...)
	y := append([]string(nil), b...)
	sort.Strings(x)
	sort.Strings(y)
	for i := range x {
		if x[i] != y[i] {
			return false
		}
	}
	return true
}

// Repo is a repository as listed.
type Repo struct {
	Name     string `json:"name"`
	Private  bool   `json:"private"`
	Archived bool   `json:"archived"`
	Fork     bool   `json:"fork"`
}

// Result is one repository's run.
type Result struct {
	Repo     Repo
	Alerts   []Alert
	Unread   []string // kinds whose listing could not be read
	Opened   int
	Deferred int // new alerts left for a later run (the Budget)
	Updated  int
	Closed   int
	Adopted  int
	Tickets  []Issue // open tickets after the run
	Messages []string
}

// Budget bounds the new tickets of a run: PerRepo in each repository and
// Total over the run, so a first listing of hundreds of alerts opens them
// over several hours, the highest priority first, without tripping GitHub's
// content-creation limits. Updates and closes are never bounded. A nil
// Budget is no bound.
type Budget struct {
	PerRepo, Total int
}

// Defaults for the command's flags.
const (
	DefaultPerRepo = 3
	DefaultTotal   = 30
)

// Sync reads one repository's alerts and keeps its tickets, opening new
// ones within b.
func Sync(g GitHub, r Repo, now time.Time, dry bool, b *Budget) (Result, error) {
	res := Result{Repo: r}
	full := Org + "/" + r.Name
	read := map[string]bool{}
	for _, k := range []string{CodeScanning, Dependabot, SecretScanning} {
		raws, err := list[rawAlert](g, "repos/"+full+"/"+kindPath[k]+"?state=open")
		if err != nil {
			if s := status(err); s == 404 || s == 403 {
				// off, no analysis yet, or no permission: nothing to sync, nothing to close
				res.Unread = append(res.Unread, fmt.Sprintf("%s (HTTP %d)", k, s))
				continue
			}
			return res, err
		}
		read[k] = true
		for _, x := range raws {
			res.Alerts = append(res.Alerts, x.alert(k))
		}
	}
	if len(read) == 0 && len(res.Alerts) == 0 {
		return res, nil
	}
	tickets, err := list[Issue](g, "repos/"+full+"/issues?state=open&labels="+Label)
	if err != nil {
		return res, err
	}
	var bugs []Issue // open bug issues that may name an alert (the former bestpractices bugs)
	if len(res.Alerts) > 0 {
		if bugs, err = list[Issue](g, "repos/"+full+"/issues?state=open&labels=bug"); err != nil {
			return res, err
		}
	}
	byURL := map[string]Issue{}
	for _, t := range tickets {
		if t.PR == nil {
			if u := markerURL(t.Body); u != "" {
				byURL[u] = t
			}
		}
	}
	open := map[string]bool{}
	// the highest priority first, then the oldest, so a bounded run opens
	// what matters most
	sort.SliceStable(res.Alerts, func(i, j int) bool {
		x, y := res.Alerts[i], res.Alerts[j]
		if px, py := x.Priority(now), y.Priority(now); px != py {
			return px < py
		}
		if !x.Created.Equal(y.Created) {
			return x.Created.Before(y.Created)
		}
		if x.Kind != y.Kind {
			return x.Kind < y.Kind
		}
		return x.Number < y.Number
	})
	perRepo := 0
	for _, a := range res.Alerts {
		open[a.URL] = true
		title, body, labels := Title(a), Body(a, now), Labels(a, now)
		t, ok := byURL[a.URL]
		if !ok {
			for _, b := range bugs {
				if b.PR == nil && namesURL(b.Body, a.URL) {
					t, ok = b, true
					res.Adopted++
					break
				}
			}
		}
		if !ok {
			if b != nil && (perRepo >= b.PerRepo || b.Total <= 0) {
				res.Deferred++
				continue
			}
			perRepo++
			if b != nil {
				b.Total--
			}
			res.Opened++
			msg := fmt.Sprintf("%s alert #%d: open a ticket (%s)", a.Kind, a.Number, "priority:"+a.Priority(now))
			if !dry {
				data, err := g.do("POST", "repos/"+full+"/issues", map[string]any{"title": title, "body": body, "labels": labels})
				if err != nil {
					return res, err
				}
				var got Issue
				_ = json.Unmarshal(data, &got)
				msg = fmt.Sprintf("%s alert #%d: opened #%d (%s)", a.Kind, a.Number, got.Number, "priority:"+a.Priority(now))
				res.Tickets = append(res.Tickets, Issue{Number: got.Number, Body: body})
			}
			res.Messages = append(res.Messages, msg)
			continue
		}
		res.Tickets = append(res.Tickets, t)
		want := mergeLabels(t.labelNames(), labels)
		if t.Title == title && t.Body == body && sameSet(t.labelNames(), want) {
			continue
		}
		res.Updated++
		res.Messages = append(res.Messages, fmt.Sprintf("%s alert #%d: update #%d", a.Kind, a.Number, t.Number))
		if !dry {
			if _, err := g.do("PATCH", fmt.Sprintf("repos/%s/issues/%d", full, t.Number),
				map[string]any{"title": title, "body": body, "labels": want}); err != nil {
				return res, err
			}
		}
	}
	// close the tickets whose alert is no longer open, only for a kind read
	kindOf := func(u string) string {
		for k, p := range kindPath {
			if strings.Contains(u, "/security/"+strings.TrimSuffix(p, "/alerts")+"/") {
				return k
			}
		}
		return ""
	}
	urls := make([]string, 0, len(byURL))
	for u := range byURL {
		urls = append(urls, u)
	}
	sort.Strings(urls)
	for _, u := range urls {
		if open[u] || !read[kindOf(u)] {
			continue
		}
		t := byURL[u]
		res.Closed++
		res.Messages = append(res.Messages, fmt.Sprintf("close #%d: its alert is no longer open", t.Number))
		if !dry {
			c := "The alert " + u + " is no longer open (fixed, or dismissed by the maintainer): closing this ticket." + Footer
			if _, err := g.do("POST", fmt.Sprintf("repos/%s/issues/%d/comments", full, t.Number), map[string]any{"body": c}); err != nil {
				return res, err
			}
			if _, err := g.do("PATCH", fmt.Sprintf("repos/%s/issues/%d", full, t.Number),
				map[string]any{"state": "closed", "state_reason": "completed"}); err != nil {
				return res, err
			}
		}
	}
	return res, nil
}

// Repos lists the org's unarchived repositories that are not forks, or the
// named ones.
func Repos(g GitHub, names []string) ([]Repo, error) {
	if len(names) == 0 {
		all, err := list[Repo](g, "orgs/"+Org+"/repos?type=all&sort=full_name")
		if err != nil {
			return nil, err
		}
		var out []Repo
		for _, r := range all {
			if !r.Archived && !r.Fork {
				out = append(out, r)
			}
		}
		return out, nil
	}
	var out []Repo
	for _, n := range names {
		if !repoName.MatchString(n) {
			return nil, fmt.Errorf("%q is not a repository name", n)
		}
		data, err := g.do("GET", "repos/"+Org+"/"+n, nil)
		if err != nil {
			return nil, err
		}
		var r Repo
		if err := json.Unmarshal(data, &r); err != nil {
			return nil, err
		}
		out = append(out, r)
	}
	return out, nil
}

// fixesMerged counts the security-autofix PRs merged in the last 7 days.
func fixesMerged(g GitHub, repo string, now time.Time) (int, error) {
	prs, err := list[struct {
		Merged *time.Time `json:"merged_at"`
		Head   struct {
			Ref string `json:"ref"`
		} `json:"head"`
	}](g, "repos/"+Org+"/"+repo+"/pulls?state=closed&sort=updated&direction=desc")
	if err != nil {
		return 0, err
	}
	n := 0
	for _, p := range prs {
		if p.Merged != nil && now.Sub(*p.Merged) <= 7*24*time.Hour && strings.HasPrefix(p.Head.Ref, "claude/security-fix-") {
			n++
		}
	}
	return n, nil
}

// ReportBody is the summary issue's body.
func ReportBody(results []Result, fixes map[string]int, m *repomask.Masker, now time.Time) string {
	lines := []string{"## Open security alerts", "",
		"Kept by the `security-alerts` task (swarm-routing/.github#629), refreshed every week. One ticket per alert lives in " +
			"the alert's repository (label `security`).", "",
		"| Repository | Critical | High | Medium | Low | Secrets | Oldest (days) | Past SLA | Fixes merged (7 days) | Waiting for the maintainer |",
		"|---|---|---|---|---|---|---|---|---|---|"}
	total := 0
	for _, r := range results {
		c := map[string]int{}
		oldest, past, waiting := 0, 0, 0
		for _, a := range r.Alerts {
			if a.Kind == SecretScanning {
				c["secret"]++
			} else {
				c[a.Severity]++
			}
			if d := int(a.Age(now).Hours() / 24); d > oldest {
				oldest = d
			}
			if a.PastSLA(now) {
				past++
			}
			if a.Kind == SecretScanning || a.Policy() {
				waiting++
			}
		}
		if len(r.Alerts) == 0 && fixes[r.Repo.Name] == 0 && len(r.Unread) == 0 {
			continue
		}
		total += len(r.Alerts)
		name := m.Repo(r.Repo.Name, r.Repo.Private, Org+"/"+r.Repo.Name, r.Repo.Name)
		if len(r.Unread) > 0 {
			name += " (unread: " + strings.Join(r.Unread, ", ") + ")"
		}
		lines = append(lines, fmt.Sprintf("| %s | %d | %d | %d | %d | %d | %d | %d | %d | %d |", name,
			c["critical"], c["high"], c["medium"], c["low"], c["secret"], oldest, past, fixes[r.Repo.Name], waiting))
	}
	if total == 0 {
		lines = append(lines, "| (none) | 0 | 0 | 0 | 0 | 0 | 0 | 0 | 0 | 0 |")
	}
	lines = append(lines, "",
		fmt.Sprintf("SLA: critical %d days, medium or higher %d days; past it, the ticket is P1. \"Waiting for the maintainer\": "+
			"leaked secrets to rotate and policy findings to decide (a settings change or a dismissal with its reason).",
			CriticalDays, EscalateDays),
		"", "Updated "+now.UTC().Format("2006-01-02")+".")
	return strings.Join(lines, "\n") + Footer
}

// Report creates or updates the summary issue in swarm-routing/.github.
func Report(g GitHub, body string, dry bool) (string, error) {
	issues, err := list[Issue](g, "repos/"+Org+"/.github/issues?state=open&labels="+Label)
	if err != nil {
		return "", err
	}
	for _, i := range issues {
		if i.Title == ReportTitle && i.PR == nil {
			if i.Body == body {
				return fmt.Sprintf("report: #%d unchanged", i.Number), nil
			}
			if dry {
				return fmt.Sprintf("report: would update #%d", i.Number), nil
			}
			_, err := g.do("PATCH", fmt.Sprintf("repos/%s/.github/issues/%d", Org, i.Number), map[string]any{"body": body})
			return fmt.Sprintf("report: updated #%d", i.Number), err
		}
	}
	if dry {
		return "report: would open it", nil
	}
	data, err := g.do("POST", "repos/"+Org+"/.github/issues", map[string]any{"title": ReportTitle, "body": body,
		"labels": []string{Label, "chore", "ci", "model:haiku-5.5", "priority:P2"}})
	if err != nil {
		return "", err
	}
	var got Issue
	_ = json.Unmarshal(data, &got)
	return fmt.Sprintf("report: opened #%d", got.Number), nil
}

const usage = `usage: security-alerts [--repos A,B] [--report] [--dry-run] [--max-new N] [--max-new-per-repo N] [--now RFC3339]

Keeps one issue (label security) per open code-scanning, Dependabot and
secret-scanning alert in every org repository (or --repos), with the org
App's token in GH_TOKEN; --report also refreshes the summary issue in
swarm-routing/.github. A run opens at most --max-new new tickets (default 30),
at most --max-new-per-repo in one repository (default 3), the highest
priority first; the rest wait for the next run. --dry-run only reads.
Exit 0 done, 1 failed, 2 usage.`

// Main is the command.
func Main(args []string, getenv func(string) string, client *http.Client, api string, stdout, stderr io.Writer) int {
	dry, report, nowS := false, false, ""
	budget := Budget{PerRepo: DefaultPerRepo, Total: DefaultTotal}
	var names []string
	for i := 0; i < len(args); i++ {
		switch a := args[i]; {
		case a == "--dry-run":
			dry = true
		case a == "--report":
			report = true
		case (a == "--max-new" || a == "--max-new-per-repo") && i+1 < len(args):
			n, err := strconv.Atoi(args[i+1])
			if err != nil || n < 0 {
				fmt.Fprintln(stderr, usage)
				return 2
			}
			if a == "--max-new" {
				budget.Total = n
			} else {
				budget.PerRepo = n
			}
			i++
		case (a == "--repos" || a == "--now") && i+1 < len(args):
			if a == "--repos" {
				for _, n := range strings.Split(args[i+1], ",") {
					if n = strings.TrimSpace(n); n != "" {
						names = append(names, n)
					}
				}
			} else {
				nowS = args[i+1]
			}
			i++
		case a == "-h" || a == "--help":
			fmt.Fprintln(stdout, usage)
			return 0
		default:
			fmt.Fprintln(stderr, usage)
			return 2
		}
	}
	now := time.Now().UTC()
	if nowS != "" {
		var err error
		if now, err = time.Parse(time.RFC3339, nowS); err != nil {
			fmt.Fprintln(stderr, "security-alerts: --now:", err)
			return 2
		}
	}
	token := getenv("GH_TOKEN")
	if token == "" && !dry {
		fmt.Fprintln(stdout, "security-alerts: no GH_TOKEN: dry run")
		dry = true
	}
	g := GitHub{API: api, Token: token, Client: client}
	var m repomask.Masker
	repos, err := Repos(g, names)
	if err != nil {
		fmt.Fprintln(stderr, "security-alerts:", m.Error(err))
		return 1
	}
	var results []Result
	failed, alerts, opened, updated, closed, unread, deferred := 0, 0, 0, 0, 0, 0, 0
	fixes := map[string]int{}
	for _, r := range repos {
		name := m.Repo(r.Name, r.Private, Org+"/"+r.Name, r.Name)
		res, err := Sync(g, r, now, dry, &budget)
		for _, msg := range res.Messages {
			fmt.Fprintf(stdout, "%s: %s\n", name, m.Scrub(msg))
		}
		if err != nil {
			failed++
			fmt.Fprintf(stdout, "%s: FAILED: %s\n", name, m.Error(err))
			continue
		}
		if report {
			n, err := fixesMerged(g, r.Name, now)
			if err != nil {
				fmt.Fprintf(stdout, "%s: fixes merged: %s\n", name, m.Error(err))
			}
			fixes[r.Name] = n
		}
		if len(res.Unread) > 0 {
			unread++
			fmt.Fprintf(stdout, "%s: unreadable: %s\n", name, strings.Join(res.Unread, ", "))
		}
		alerts += len(res.Alerts)
		opened += res.Opened
		deferred += res.Deferred
		updated += res.Updated
		closed += res.Closed
		results = append(results, res)
	}
	verb := ""
	if dry {
		verb = "would have "
	}
	fmt.Fprintf(stdout, "security-alerts: %d repositories, %d open alerts; %sopened %d, updated %d, closed %d tickets, "+
		"%d new left for later runs; %d with an unreadable listing, %d failed\n", len(repos), alerts, verb, opened, updated, closed,
		deferred, unread, failed)
	if report {
		out, err := Report(g, ReportBody(results, fixes, &m, now), dry)
		if err != nil {
			fmt.Fprintln(stderr, "security-alerts: report:", m.Error(err))
			return 1
		}
		fmt.Fprintln(stdout, out)
	}
	if failed > 0 {
		return 1
	}
	return 0
}
