// Package securityalerts keeps one ticket per open security alert in every
// org repository (swarm-routing/.github#629). With the org App's token it
// lists every open code-scanning (CodeQL, Scorecard, ...), Dependabot and
// secret-scanning alert, and in the alert's repository opens, updates in
// place or closes one issue per alert:
//
//   - labels `security`, `bug`, `ci`, a model suggestion and a priority from
//     the severity: critical or high P1, medium P2, low P3, a leaked secret
//     always P1;
//   - the alert's URL in a marker comment, matched to a boundary (#621), so
//     alert 1's issue never stands for alert 10;
//   - the SLA: an alert open more than CriticalDays (critical) or
//     EscalateDays (medium or higher) is past its SLA and its issue is P1;
//     the weekly bestpractices check withdraws its answers on the same
//     thresholds;
//   - closed, with a comment, when the alert is no longer open (fixed or
//     dismissed), and only when its kind's listing was read.
//
// The issue tells who acts: a code finding is fixed by the repository's
// security-autofix.yml (a test-first fix PR), a policy finding (Scorecard)
// waits for the maintainer's dismissal or a settings change, a Dependabot
// alert for Dependabot's security update, a leaked secret for the
// maintainer's rotation. An open bug issue that already names an alert's URL
// (the bestpractices check's former alert bugs) is adopted, not duplicated.
//
// Report keeps the weekly summary issue in swarm-routing/.github. Private
// repositories are named through internal/repomask in every output that
// leaves them: the log and the summary.
package securityalerts

