// Package ticketaudit is the weekly ticket audit (#730): it reads every open,
// non-epic issue of every unarchived org repository (the list comes from the
// API, so a new repository is covered) and closes, with a comment, the ones
// whose work is recorded as done:
//
//   - every Acceptance-criteria checkbox is ticked, and there is at least one;
//   - a merged PR's body says `Closes|Fixes|Resolves #N` (or the full
//     cross-repo form, or the issue's URL) for it, the issue was opened before
//     the merge and not reopened after it, and GitHub left it open;
//   - a `handoff` issue, only when a newer open `handoff` issue of the same
//     repository has a "Supersedes #N" line for it (closed as not planned).
//
// It never closes an issue with an unticked box (boxes inside a <details>
// block or a code fence are superseded text and do not count; a fence or a
// <details> that never closes keeps the issue open), nor one labelled `hold`,
// `epic`, `security` or `rcapa`, nor one labelled `release:vX.Y.Z` while that
// repository has no release vX.Y.Z. At most MaxCloses issues are closed a run.
// Report-only: the issues at least 80% ticked and the issues with no
// checkbox, in one summary issue in swarm-routing/.github, ReportTitle,
// updated in place. A private repository is never named or linked, in the
// log or the report: it is "private repository N" (internal/repomask).
//
// RCAPA tickets (rcapa.go, #952): an open `[rcapa]` issue without `rcapa`
// gets its form's labels; one older than 2 days with no logged step and no
// linked PR is listed in the report, not changed.
package ticketaudit

import (
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"regexp"
	"sort"
	"strings"
	"time"

	"github.com/swarm-routing/.github/internal/github"
	"github.com/swarm-routing/.github/internal/repomask"
)

const (
	// Org is the organization audited.
	Org = "swarm-routing"
	// ReportTitle is the summary issue's title in swarm-routing/.github.
	ReportTitle = "[tickets] audit"
	// MaxCloses bounds the issues one run closes (golden rule 7); each is a
	// comment and a close. The rest waits for the next run.
	MaxCloses = 20
	// NearDone is the ticked share from which an issue is listed as nearly done.
	NearDone = 0.8
	// Footer ends every comment and the report.
	Footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
	// maxPages bounds a listing (100 items a page); the closed-PR listing of
	// one repository stops there and reads no older PR.
	maxPages = 30
	// maxReport bounds the report body (GitHub refuses one over 65536 characters).
	maxReport = 60000
)

// keepLabels are never closed by the audit, with the reason.
var keepLabels = map[string]string{
	"hold":     "labelled hold",
	"epic":     "an epic",
	"security": "a security ticket (closed by security-alerts)",
	"rcapa":    "an RCAPA (open until a release carries the fix)",
}

var (
	repoName     = regexp.MustCompile(`^[A-Za-z0-9_.-]+$`)
	releaseLabel = regexp.MustCompile(`^release:(v\d+\.\d+\.\d+)$`)
)

// alwaysPrivate names the repositories masked even if GitHub calls them
// public: the private paper library is never named or linked.
var alwaysPrivate = map[string]bool{"papers": true}

// GitHub is the REST client: base URL, token, HTTP client.
type GitHub struct {
	API    string
	Token  string
	Client *http.Client
}

func (g GitHub) rest() github.Client {
	return github.Client{API: g.API, Token: g.Token, UserAgent: "swarm-routing-ticket-audit", HTTP: g.Client}
}

func (g GitHub) do(method, path string, body any) ([]byte, error) {
	return g.rest().Do(method, path, body)
}

func list[T any](g GitHub, path string) ([]T, error) {
	return github.List[T](g.rest(), path, maxPages)
}

// listUpTo reads at most maxPages pages; truncated says older items were left.
func listUpTo[T any](g GitHub, path string) (all []T, truncated bool, err error) {
	for page := 1; page <= maxPages; page++ {
		data, err := g.do("GET", fmt.Sprintf("%s&per_page=100&page=%d", path, page), nil)
		if err != nil {
			return nil, false, err
		}
		var got []T
		if err := json.Unmarshal(data, &got); err != nil {
			return nil, false, fmt.Errorf("GET %s: %v", path, err)
		}
		all = append(all, got...)
		if len(got) < 100 {
			return all, false, nil
		}
	}
	return all, true, nil
}

// Repo is the part of a repository the audit reads.
type Repo struct {
	Name      string `json:"name"`
	FullName  string `json:"full_name"`
	Archived  bool   `json:"archived"`
	Private   bool   `json:"private"`
	Fork      bool   `json:"fork"`
	HasIssues bool   `json:"has_issues"`
}

func (r Repo) private() bool { return r.Private || alwaysPrivate[strings.ToLower(r.Name)] }

type label struct {
	Name string `json:"name"`
}

// Issue is the part of an issue the audit reads.
type Issue struct {
	Number    int       `json:"number"`
	Title     string    `json:"title"`
	Body      string    `json:"body"`
	Labels    []label   `json:"labels"`
	CreatedAt time.Time `json:"created_at"`
	PR        *struct{} `json:"pull_request"`
}

func (i Issue) has(name string) bool {
	for _, l := range i.Labels {
		if strings.EqualFold(l.Name, name) {
			return true
		}
	}
	return false
}

type pull struct {
	Number   int        `json:"number"`
	Body     string     `json:"body"`
	MergedAt *time.Time `json:"merged_at"`
}

type event struct {
	Event     string    `json:"event"`
	CreatedAt time.Time `json:"created_at"`
}

// closer is a merged PR that says it closes an issue.
type closer struct {
	Repo     Repo
	Number   int
	MergedAt time.Time
}

// Item is one open issue and what the audit made of it.
type Item struct {
	Repo   Repo
	Issue  Issue
	Boxes  Boxes
	Action string // "close", "close-superseded" or "" (kept)
	Why    string // the reason, for the comment and the log
	By     *closer
	SupBy  int // the newer handoff that supersedes it
	Done   bool
}

// Result counts one run.
type Result struct {
	Repos, Issues, Closed, Deferred, Failed int
	Truncated                               []string // repositories whose closed-PR listing stopped at the page cap
	Labelled                                []string // the [rcapa] tickets given their form's labels (rcapa.go)
	Unrecorded                              []string // the RCAPA tickets with no logged step and no linked PR
	UnrecordedPrivate                       int
	Items                                   []*Item
	Report                                  string
}

// Repos is every unarchived, non-fork org repository with issues, or the named ones.
func Repos(g GitHub, names []string) ([]Repo, error) {
	var all []Repo
	if len(names) == 0 {
		got, err := list[Repo](g, "orgs/"+Org+"/repos?type=all&sort=full_name")
		if err != nil {
			return nil, err
		}
		all = got
	} else {
		for _, n := range names {
			if !repoName.MatchString(n) {
				return nil, fmt.Errorf("%q is not a repository name", n)
			}
			data, err := g.do("GET", "repos/"+Org+"/"+n, nil)
			if err != nil {
				return nil, err
			}
			var r Repo
			if err := json.Unmarshal(data, &r); err != nil {
				return nil, err
			}
			all = append(all, r)
		}
	}
	var out []Repo
	for _, r := range all {
		if !r.Archived && !r.Fork && r.HasIssues && r.FullName == Org+"/"+r.Name && repoName.MatchString(r.Name) {
			out = append(out, r)
		}
	}
	sort.Slice(out, func(i, j int) bool { return strings.ToLower(out[i].Name) < strings.ToLower(out[j].Name) })
	return out, nil
}

// auditor holds one run's state.
type auditor struct {
	g        GitHub
	now      time.Time
	dry      bool
	mask     *repomask.Masker
	out      io.Writer
	releases map[string]bool // "repo vX.Y.Z" -> cut
}

func (a *auditor) label(r Repo) string { return a.mask.Repo(r.Name, r.private(), r.FullName, r.Name) }

// cut says whether repo has a published release named tag (an unreadable
// answer counts as not cut: the issue stays open).
func (a *auditor) cut(r Repo, tag string) bool {
	k := r.Name + " " + tag
	if v, ok := a.releases[k]; ok {
		return v
	}
	data, err := a.g.do("GET", fmt.Sprintf("repos/%s/releases/tags/%s", r.FullName, tag), nil)
	var rel struct {
		Draft bool `json:"draft"`
	}
	ok := err == nil && json.Unmarshal(data, &rel) == nil && !rel.Draft
	a.releases[k] = ok
	return ok
}

// held is why the labels keep an issue open, or "".
func (a *auditor) held(r Repo, i Issue) string {
	names := make([]string, 0, len(i.Labels))
	for _, l := range i.Labels {
		names = append(names, strings.ToLower(l.Name))
	}
	sort.Strings(names)
	for _, n := range names {
		if why, ok := keepLabels[n]; ok {
			return why
		}
		if m := releaseLabel.FindStringSubmatch(n); m != nil && !a.cut(r, m[1]) {
			return "labelled " + n + ", not released yet"
		}
	}
	return ""
}

// reopenedAfter says whether the issue was reopened at or after t (an
// unreadable event list counts as reopened: the issue stays open).
func (a *auditor) reopenedAfter(r Repo, n int, t time.Time) bool {
	evs, err := list[event](a.g, fmt.Sprintf("repos/%s/issues/%d/events?", r.FullName, n))
	if err != nil {
		return true
	}
	for _, e := range evs {
		if e.Event == "reopened" && !e.CreatedAt.Before(t) {
			return true
		}
	}
	return false
}

// closers maps every org issue a merged PR closes to that PR (the earliest merge).
func (a *auditor) closers(repos []Repo, res *Result) (map[Ref]closer, error) {
	out := map[Ref]closer{}
	for _, r := range repos {
		prs, truncated, err := listUpTo[pull](a.g, fmt.Sprintf("repos/%s/pulls?state=closed&sort=created&direction=desc", r.FullName))
		if err != nil {
			return nil, fmt.Errorf("%s: closed pull requests: %w", a.label(r), a.mask.Error(err))
		}
		if truncated {
			res.Truncated = append(res.Truncated, a.label(r))
		}
		for _, p := range prs {
			if p.MergedAt == nil {
				continue
			}
			for _, ref := range ClosingRefs(p.Body, r.Name) {
				ref.Repo = strings.ToLower(ref.Repo)
				if c, ok := out[ref]; !ok || p.MergedAt.Before(c.MergedAt) {
					out[ref] = closer{Repo: r, Number: p.Number, MergedAt: *p.MergedAt}
				}
			}
		}
	}
	return out, nil
}

// decide applies the rules to one issue.
func (a *auditor) decide(it *Item, closedBy map[Ref]closer, supersededBy map[int]int) {
	r, i := it.Repo, it.Issue
	it.Boxes = Count(i.Body)
	if why := a.held(r, i); why != "" {
		it.Why = "kept: " + why
		return
	}
	if it.Boxes.Unparseable {
		it.Why = "kept: " + it.Boxes.UnparseableReason
		return
	}
	if n := it.Boxes.Unticked(); n > 0 {
		it.Why = fmt.Sprintf("kept: %d of %d boxes unticked", n, it.Boxes.Total)
		return
	}
	if i.has("handoff") {
		if by, ok := supersededBy[i.Number]; ok {
			it.Action, it.SupBy = "close-superseded", by
			it.Why = fmt.Sprintf("superseded by the newer handoff #%d", by)
			return
		}
		it.Why = "kept: a handoff no newer handoff supersedes"
		return
	}
	if it.Boxes.AC > 0 && it.Boxes.ACTicked == it.Boxes.AC {
		it.Action = "close"
		it.Why = fmt.Sprintf("every acceptance-criteria box ticked (%d of %d)", it.Boxes.ACTicked, it.Boxes.AC)
		return
	}
	if c, ok := closedBy[Ref{Repo: strings.ToLower(r.Name), Num: i.Number}]; ok && i.CreatedAt.Before(c.MergedAt) {
		if a.reopenedAfter(r, i.Number, c.MergedAt) {
			it.Why = "kept: reopened after the PR that closed it merged"
			return
		}
		it.Action, it.By = "close", &c
		it.Why = "closed by a merged pull request"
		return
	}
	if it.Boxes.Total == 0 {
		it.Why = "kept: no checkbox"
	} else {
		it.Why = "kept: every box ticked, but none under an Acceptance criteria heading"
	}
}

// comment is the closing comment for one issue.
func (a *auditor) comment(it *Item) string {
	switch {
	case it.Action == "close-superseded":
		return fmt.Sprintf("The newer handoff #%d says it supersedes this one, so the weekly ticket audit closes this handoff "+
			"as not planned: continue from #%d. Reopen it if it still carries work of its own.", it.SupBy, it.SupBy) + Footer
	case it.By != nil:
		pr := "a merged pull request of a private org repository"
		if !it.By.Repo.private() || it.By.Repo.Name == it.Repo.Name {
			pr = fmt.Sprintf("%s/%s#%d", Org, it.By.Repo.Name, it.By.Number)
			if it.By.Repo.Name == it.Repo.Name {
				pr = fmt.Sprintf("#%d", it.By.Number)
			}
		}
		return fmt.Sprintf("%s (merged %s) says it closes this issue, and GitHub left it open; no checkbox here is unticked "+
			"and it was not reopened since, so the weekly ticket audit closes it as completed. Reopen it if work remains.",
			pr, it.By.MergedAt.UTC().Format("2006-01-02")) + Footer
	default:
		return fmt.Sprintf("Every acceptance-criteria box is ticked (%d of %d) and no other box is open, so the weekly ticket "+
			"audit closes this issue as completed. Reopen it if work remains: an unticked box keeps an issue open.",
			it.Boxes.ACTicked, it.Boxes.AC) + Footer
	}
}

func (a *auditor) close(it *Item) error {
	reason := "completed"
	if it.Action == "close-superseded" {
		reason = "not_planned"
	}
	path := fmt.Sprintf("repos/%s/issues/%d", it.Repo.FullName, it.Issue.Number)
	if _, err := a.g.do("POST", path+"/comments", map[string]any{"body": a.comment(it)}); err != nil {
		return err
	}
	_, err := a.g.do("PATCH", path, map[string]any{"state": "closed", "state_reason": reason})
	return err
}

// name is how the log and the report show an issue: a public one by its
// full reference, a private one by its repository's label alone.
func (a *auditor) name(it *Item) string {
	if it.Repo.private() {
		return a.label(it.Repo)
	}
	return fmt.Sprintf("%s/%s#%d", Org, it.Repo.Name, it.Issue.Number)
}

// Run audits every repository (or the named ones), closes what the rules
// allow (none in a dry run) and refreshes the report.
func Run(g GitHub, names []string, now time.Time, dry bool, out io.Writer) (Result, error) {
	var res Result
	var mask repomask.Masker
	a := &auditor{g: g, now: now, dry: dry, mask: &mask, out: out, releases: map[string]bool{}}
	repos, err := Repos(g, names)
	if err != nil {
		return res, mask.Error(err)
	}
	res.Repos = len(repos)
	for _, r := range repos {
		a.label(r) // number the private repositories in the order of the listing
	}
	closedBy, err := a.closers(repos, &res)
	if err != nil {
		return res, err
	}
	var items []*Item
	for _, r := range repos {
		issues, err := list[Issue](g, fmt.Sprintf("repos/%s/issues?state=open&sort=created&direction=asc", r.FullName))
		if err != nil {
			fmt.Fprintf(out, "%s: error: %v\n", a.label(r), mask.Error(err))
			res.Failed++
			continue
		}
		var open []Issue
		for _, i := range issues {
			if i.PR == nil && !i.has("epic") && !(r.Name == ".github" && i.Title == ReportTitle) {
				open = append(open, i)
			}
		}
		a.rcapa(r, open, &res)
		// a newer open handoff's "Supersedes #N" lines, for an older handoff of this repository
		supersededBy := map[int]int{}
		for _, i := range open {
			if !i.has("handoff") {
				continue
			}
			for _, n := range Superseded(i.Body, r.Name) {
				if n < i.Number {
					if prev, ok := supersededBy[n]; !ok || i.Number > prev {
						supersededBy[n] = i.Number
					}
				}
			}
		}
		for _, i := range open {
			it := &Item{Repo: r, Issue: i}
			a.decide(it, closedBy, supersededBy)
			items = append(items, it)
		}
	}
	res.Issues = len(items)
	budget := MaxCloses
	for _, it := range items {
		if it.Action == "" {
			continue
		}
		if budget <= 0 {
			res.Deferred++
			fmt.Fprintf(out, "%s: %s; deferred (%d closes a run)\n", a.name(it), it.Why, MaxCloses)
			continue
		}
		budget--
		if dry {
			fmt.Fprintf(out, "%s: %s; dry run: would close\n", a.name(it), it.Why)
			res.Closed++
			it.Done = true
			continue
		}
		if err := a.close(it); err != nil {
			fmt.Fprintf(out, "%s: close failed: %v\n", a.name(it), mask.Error(err))
			res.Failed++
			continue
		}
		fmt.Fprintf(out, "%s: %s; closed\n", a.name(it), it.Why)
		res.Closed++
		it.Done = true
	}
	res.Items = items
	body := ReportBody(a, &res)
	near, none := 0, 0
	for _, it := range items {
		switch {
		case it.Done:
		case it.Boxes.Total == 0 && !it.Boxes.Unparseable:
			none++
		case it.Boxes.Total > 0 && it.Boxes.Ratio() >= NearDone:
			near++
			if !it.Repo.private() {
				fmt.Fprintf(out, "nearly done: %s (%d/%d)\n", a.name(it), it.Boxes.Ticked, it.Boxes.Total)
			}
		}
	}
	report, rerr := Report(g, body, dry)
	res.Report = report
	verb := "closed"
	if dry {
		verb = "would close"
	}
	fmt.Fprintf(out, "ticket-audit: %d repositories, %d open issues, %s %d", res.Repos, res.Issues, verb, res.Closed)
	if res.Deferred > 0 {
		fmt.Fprintf(out, ", %d deferred to the next run", res.Deferred)
	}
	fmt.Fprintf(out, "; nearly done (>= %d%% ticked) %d, no checkbox %d; rcapa labelled %d, unrecorded %d; %s\n",
		int(NearDone*100), near, none, len(res.Labelled), len(res.Unrecorded)+res.UnrecordedPrivate, report)
	if rerr != nil {
		return res, fmt.Errorf("the report: %v", rerr)
	}
	if res.Failed > 0 {
		return res, fmt.Errorf("%d failures", res.Failed)
	}
	return res, nil
}

// ReportBody is the summary issue's body.
func ReportBody(a *auditor, res *Result) string {
	var closed, deferred, near, none []string
	privNear, privNone := map[string]int{}, map[string]int{}
	for _, it := range res.Items {
		pct := 0
		if it.Boxes.Total > 0 {
			pct = it.Boxes.Ticked * 100 / it.Boxes.Total
		}
		switch {
		case it.Done:
			closed = append(closed, fmt.Sprintf("- %s: %s", a.name(it), it.Why))
		case it.Action != "":
			deferred = append(deferred, fmt.Sprintf("- %s: %s", a.name(it), it.Why))
		case it.Boxes.Total == 0 && !it.Boxes.Unparseable:
			if it.Repo.private() {
				privNone[a.label(it.Repo)]++
			} else {
				none = append(none, a.name(it))
			}
		case it.Boxes.Total > 0 && it.Boxes.Ratio() >= NearDone:
			if it.Repo.private() {
				privNear[a.label(it.Repo)]++
			} else {
				near = append(near, fmt.Sprintf("- %s: %d of %d ticked (%d%%)", a.name(it), it.Boxes.Ticked, it.Boxes.Total, pct))
			}
		}
	}
	for _, p := range sortedKeys(privNear) {
		near = append(near, fmt.Sprintf("- %s: %d issues", p, privNear[p]))
	}
	for _, p := range sortedKeys(privNone) {
		none = append(none, fmt.Sprintf("%s (%d issues)", p, privNone[p]))
	}
	verb := "Closed"
	if a.dry {
		verb = "Would close (dry run)"
	}
	lines := []string{"## Ticket audit", "",
		"Kept by the weekly `ticket-audit` task (swarm-routing/.github#730; CONTRIBUTING \"Issues\"). It closes an open, " +
			"non-epic issue only when every acceptance-criteria box is ticked, or a merged PR says it closes the issue and " +
			"GitHub left it open; a `handoff` only when a newer open handoff says it supersedes it. An unticked box, " +
			"`hold`, `epic`, `security`, `rcapa`, or a `release:vX.Y.Z` not yet released keeps an issue open. " +
			"Boxes inside `<details>` or a code fence do not count. An open `[rcapa]` issue without `rcapa` gets its " +
			"form's labels (#952).", "",
		fmt.Sprintf("%d repositories, %d open issues.", res.Repos, res.Issues), ""}
	section := func(title string, items []string) {
		lines = append(lines, fmt.Sprintf("### %s (%d)", title, len(items)), "")
		if len(items) == 0 {
			lines = append(lines, "(none)")
		}
		lines = append(lines, items...)
		lines = append(lines, "")
	}
	section(verb+" this run", closed)
	if len(deferred) > 0 {
		section(fmt.Sprintf("To close next run (over %d a run)", MaxCloses), deferred)
	}
	section(fmt.Sprintf("Nearly done: at least %d%% of the boxes ticked", int(NearDone*100)), near)
	section("RCAPA tickets given their form's labels this run", res.Labelled)
	unrec := res.Unrecorded
	if res.UnrecordedPrivate > 0 {
		unrec = append(append([]string{}, unrec...), fmt.Sprintf("- private repositories: %d tickets", res.UnrecordedPrivate))
	}
	lines = append(lines, fmt.Sprintf("### RCAPA tickets with no recorded investigation (%d)", len(res.Unrecorded)+res.UnrecordedPrivate), "",
		fmt.Sprintf("Open more than %d days, with no `rcapa-step` comment and no linked PR: log each step on the ticket "+
			"(`tools/rcapa/rcapa.py log`; CONTRIBUTING \"RCAPA\").", int(RCAPAGrace.Hours()/24)), "")
	if len(unrec) == 0 {
		lines = append(lines, "(none)")
	}
	lines = append(lines, unrec...)
	lines = append(lines, "")
	lines = append(lines, fmt.Sprintf("### No checkbox (%d)", len(none)), "",
		"These cannot be audited: give each **Acceptance criteria** checkboxes.", "")
	if len(none) == 0 {
		lines = append(lines, "(none)")
	} else {
		lines = append(lines, strings.Join(none, ", "))
	}
	lines = append(lines, "")
	if len(res.Truncated) > 0 {
		lines = append(lines, fmt.Sprintf("Closed-PR listings read to their newest %d PRs only: %s.", maxPages*100,
			strings.Join(res.Truncated, ", ")), "")
	}
	lines = append(lines, "Updated "+a.now.UTC().Format("2006-01-02")+".")
	body := strings.Join(lines, "\n")
	if len(body) > maxReport {
		body = body[:maxReport] + "\n\n(truncated)"
	}
	return body + Footer
}

func sortedKeys(m map[string]int) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// Report creates or updates the summary issue in swarm-routing/.github.
func Report(g GitHub, body string, dry bool) (string, error) {
	issues, err := list[Issue](g, "repos/"+Org+"/.github/issues?state=open")
	if err != nil {
		return "report: unreadable", err
	}
	for _, i := range issues {
		if i.Title == ReportTitle && i.PR == nil {
			if sameReport(i.Body, body) {
				return fmt.Sprintf("report: #%d unchanged", i.Number), nil
			}
			if dry {
				return fmt.Sprintf("report: would update #%d", i.Number), nil
			}
			_, err := g.do("PATCH", fmt.Sprintf("repos/%s/.github/issues/%d", Org, i.Number), map[string]any{"body": body})
			return fmt.Sprintf("report: updated #%d", i.Number), err
		}
	}
	if dry {
		return "report: would open it", nil
	}
	data, err := g.do("POST", "repos/"+Org+"/.github/issues", map[string]any{"title": ReportTitle, "body": body,
		"labels": []string{"chore", "ci", "model:haiku-5.5", "priority:P3"}})
	if err != nil {
		return "report: open failed", err
	}
	var got Issue
	_ = json.Unmarshal(data, &got)
	return fmt.Sprintf("report: opened #%d", got.Number), nil
}

var updatedLine = regexp.MustCompile(`(?m)^Updated \d{4}-\d{2}-\d{2}\.$`)

// sameReport compares two bodies without their date line, so a week with no
// change writes nothing.
func sameReport(a, b string) bool {
	return updatedLine.ReplaceAllString(strings.ReplaceAll(a, "\r\n", "\n"), "") == updatedLine.ReplaceAllString(b, "")
}

const usage = `usage: ticket-audit [--repos A,B] [--dry-run] [--now RFC3339]

Closes the org's finished issues (every acceptance-criteria box ticked, or a
merged PR says it closes the issue and GitHub left it open; a handoff a newer
handoff supersedes), at most 20 a run, and keeps the summary issue
"[tickets] audit" in swarm-routing/.github, with GH_TOKEN (Issues write; Pull
requests and Contents read). An open "[rcapa]" issue without the rcapa label
gets its form's labels; an RCAPA ticket older than 2 days with no logged step
and no linked PR is listed. --dry-run only reads. Exit 0 done, 1 failed,
2 usage.`

// Main is the command.
func Main(args []string, getenv func(string) string, client *http.Client, api string, stdout, stderr io.Writer) int {
	dry, nowS := false, ""
	var names []string
	for i := 0; i < len(args); i++ {
		switch a := args[i]; {
		case a == "--dry-run":
			dry = true
		case (a == "--repos" || a == "--now") && i+1 < len(args):
			if a == "--repos" {
				for _, n := range strings.Split(args[i+1], ",") {
					if n = strings.TrimSpace(n); n != "" {
						names = append(names, n)
					}
				}
			} else {
				nowS = args[i+1]
			}
			i++
		case a == "-h" || a == "--help":
			fmt.Fprintln(stdout, usage)
			return 0
		default:
			fmt.Fprintln(stderr, usage)
			return 2
		}
	}
	now := time.Now().UTC()
	if nowS != "" {
		var err error
		if now, err = time.Parse(time.RFC3339, nowS); err != nil {
			fmt.Fprintln(stderr, "ticket-audit: --now:", err)
			return 2
		}
	}
	token := getenv("GH_TOKEN")
	if token == "" && !dry {
		fmt.Fprintln(stdout, "ticket-audit: no GH_TOKEN: dry run")
		dry = true
	}
	if _, err := Run(GitHub{API: api, Token: token, Client: client}, names, now, dry, stdout); err != nil {
		fmt.Fprintln(stderr, "ticket-audit:", err)
		return 1
	}
	return 0
}
