package projectsync

// Every org Project is public (maintainer decision 2026-11-22,
// swarm-routing/.github#707): each run lists every project the org owns, not
// only the generated one, and makes a private one public. When the token is
// refused that change (GitHub: "Viewer not authorized to change project
// visibility", the org's policy on who changes a project's visibility), the
// run fails and one `chore` issue in swarm-routing/.github names each such
// project and the maintainer's step; the first run that finds every project
// public closes it.

import (
	"encoding/json"
	"errors"
	"fmt"
	"strings"
)

const (
	// IssueRepo holds the issue (the org's own repository).
	IssueRepo = ".github"
	// IssueTitle is the issue's title; IssueMarker finds it among the open
	// `chore` issues.
	IssueTitle  = "chore: an org Project is private, and the bot may not make it public"
	IssueMarker = "<!-- project-sync: private org projects -->"
	issueLabel  = "chore"
)

// Footer ends every issue and comment the tool writes.
const Footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

// allPublic makes every private org project public, and keeps the issue for
// the ones the token may not change; an error when any stays private.
func (s *syncer) allPublic() error {
	projects, err := s.g.OrgProjects(Org)
	if err != nil {
		return fmt.Errorf("listing the org projects: %w", err)
	}
	var refused []OrgProject
	private := 0
	for _, p := range projects {
		if p.Public {
			continue
		}
		private++
		s.say("project #%d %q: private: %sset public", p.Number, p.Title, s.would())
		if s.dry {
			continue
		}
		if !s.write() {
			continue // the budget is spent: the next run tries again
		}
		err := s.g.GraphQL(mSetPublic, map[string]any{"p": p.ID, "public": true}, nil)
		s.g.pause()
		switch {
		case err == nil:
			s.res.MadePublic++
		case strings.Contains(err.Error(), VisibilityRefused):
			refused = append(refused, p)
		default:
			return err
		}
	}
	s.say("project-sync: %d org projects, %d private, %d made public, %d refused", len(projects), private,
		s.res.MadePublic, len(refused))
	if s.dry {
		return nil
	}
	if s.res.Deferred && len(refused) == 0 && s.res.MadePublic < private {
		return nil // some were not tried: no verdict on the issue yet
	}
	if err := s.keepIssue(refused); err != nil {
		return fmt.Errorf("the private-projects issue: %w", err)
	}
	if len(refused) > 0 {
		s.res.VisibilityRefused = true
		var names []string
		for _, p := range refused {
			names = append(names, fmt.Sprintf("#%d %q", p.Number, p.Title))
		}
		return errors.New("every org Project is public (swarm-routing/.github#707), but this token may not " +
			"change the visibility of " + strings.Join(names, ", ") + ": the maintainer's step is in the issue titled " +
			fmt.Sprintf("%q", IssueTitle))
	}
	return nil
}

// issueBody lists the projects the token may not make public.
func issueBody(refused []OrgProject) string {
	var b strings.Builder
	b.WriteString(IssueMarker + "\n## Context\n\n" +
		"Every org Project is public (maintainer decision 2026-11-22, #707; the plan is #541). " +
		"`project-sync` (org-bot.yml) found these Projects private, and GitHub refused the bot's token " +
		"the change (\"Viewer not authorized to change project visibility\"):\n\n")
	for _, p := range refused {
		fmt.Fprintf(&b, "- #%d %s: %s\n", p.Number, p.Title, p.URL)
	}
	b.WriteString("\n## The maintainer's step\n\nIn each Project above: **Settings → Visibility → Public**. " +
		"(Or let the org App change a project's visibility; then the next run makes them public itself.)\n\n" +
		"The run of `project-sync` stays red until every Project is public; the first run that finds them all " +
		"public closes this issue." + Footer)
	return b.String()
}

type issueRef struct {
	Number int    `json:"number"`
	Body   string `json:"body"`
	PR     *struct {
	} `json:"pull_request"`
}

// keepIssue opens or updates the issue when refused is not empty, and closes
// it when it is.
func (s *syncer) keepIssue(refused []OrgProject) error {
	open, err := list[issueRef](s.g, "repos/"+Org+"/"+IssueRepo+"/issues?state=open&labels="+issueLabel)
	if err != nil {
		return err
	}
	var have *issueRef
	for i := range open {
		if open[i].PR == nil && strings.Contains(open[i].Body, IssueMarker) {
			have = &open[i]
			break
		}
	}
	base := "repos/" + Org + "/" + IssueRepo + "/issues"
	if len(refused) == 0 {
		if have == nil {
			return nil
		}
		s.say("project-sync: every org project is public: closing issue #%d", have.Number)
		if _, err := s.g.do("POST", fmt.Sprintf("%s/%d/comments", base, have.Number), restVersion,
			map[string]string{"body": "Every org Project is public now: closing." + Footer}); err != nil {
			return err
		}
		_, err := s.g.do("PATCH", fmt.Sprintf("%s/%d", base, have.Number), restVersion,
			map[string]string{"state": "closed", "state_reason": "completed"})
		return err
	}
	body := issueBody(refused)
	if have == nil {
		data, err := s.g.do("POST", base, restVersion,
			map[string]any{"title": IssueTitle, "body": body, "labels": []string{issueLabel}})
		if err != nil {
			return err
		}
		var n issueRef
		_ = json.Unmarshal(data, &n)
		s.say("project-sync: opened issue #%d for the maintainer's step", n.Number)
		return nil
	}
	if have.Body == body {
		s.say("project-sync: issue #%d unchanged", have.Number)
		return nil
	}
	s.say("project-sync: updated issue #%d", have.Number)
	_, err = s.g.do("PATCH", fmt.Sprintf("%s/%d", base, have.Number), restVersion, map[string]string{"body": body})
	return err
}
