// cryptoUse is what in a source file means the software uses cryptography;
// hashlib alone (a checksum of a download) does not: the owner sets
// bestpractices_crypto = true if it is more than that.
var cryptoUse = regexp.MustCompile(
	`(?m)#\s*include\s*[<"](openssl|sodium|mbedtls|wolfssl|gnutls|nettle|cryptopp|botan)\b` +
		`|^\s*(import|from)\s+(ssl|hmac|secrets|cryptography|Crypto|nacl|OpenSSL)\b`)

