"""Read an issue's acceptance criteria, tick them, and close it with evidence.

Usage:
  criteria.py criteria REPO#N
  criteria.py tick REPO#N --match TEXT [--dry-run]
  criteria.py close REPO#N --evidence FILE [--tick TEXT]... [--partial] [--dry-run]
  criteria.py --self-test

REPO is a swarm-routing repository, bare (`.github#1007`) or in full
(`swarm-routing/.github#1007`).

`criteria` prints the issue's checkboxes as JSON: every `- [ ]` / `- [x]`
line (also `*`, `+` and numbered items, indented or not) outside ``` and ~~~
fences, with its text and whether it is ticked, and the count left open.

`tick` ticks the one checkbox whose text contains TEXT as a plain substring
(no glob, regex or shell meaning: `[ ]` in TEXT is three characters). It
refuses when no checkbox, or more than one, contains it; a box already ticked
is reported and left. The body is edited by position, never by substitution,
so a bracket or `$` in it cannot change what is written
(swarm-routing/.github#1007: shell substitution treated `[ ]` as a glob and
silently ticked nothing).

`close` posts FILE's text as the evidence comment (the Claude Code footer
added when missing), ticks each `--tick TEXT` as `tick` does, then closes the
issue as completed. It refuses, before writing anything, when a criterion
would stay unticked, unless `--partial`: then the comment lists the open ones
and the issue is closed all the same. It refuses a closed issue, an empty
FILE and a `--tick` that matches no box or several.

`--dry-run` prints the requests (JSON) instead of sending them, for a session
whose `gh` cannot write issues. GitHub is read through `gh api` (the caller's
login, or GH_TOKEN). Stdlib only.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

ORG = "swarm-routing"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
BOX = re.compile(r"^(\s*(?:[-*+]|\d+[.)])\s+)\[([ xX])\](\s+|$)(.*)$")
FENCE = re.compile(r"^\s*(```|~~~)")


class GhError(SystemExit):
    def __init__(self, path, stderr):
        super().__init__(f"gh api {path}: {stderr}")


def gh_api(method, path, body=None):
    cmd = ["gh", "api", "-X", method, path]
    if body is not None:
        cmd += ["--input", "-"]
    r = subprocess.run(
        cmd, input=None if body is None else json.dumps(body), capture_output=True, text=True
    )
    if r.returncode != 0:
        raise GhError(path, r.stderr.strip())
    return json.loads(r.stdout) if r.stdout.strip() else None


# --- the body ---------------------------------------------------------------


def parse_ref(ref):
    """REPO#N -> (repo name, number); only the org's repositories."""
    m = re.match(r"^(?:([\w.-]+)/)?([\w.-]+)#(\d+)$", ref or "")
    if not m or (m.group(1) and m.group(1) != ORG):
        raise SystemExit(f"{ref}: not a {ORG} issue (REPO#N)")
    return m.group(2), int(m.group(3))


def boxes(body):
    """[(line index, ticked, text)] of the body's checkboxes outside code fences."""
    out, fence = [], None
    for i, line in enumerate((body or "").split("\n")):
        f = FENCE.match(line)
        if f:
            if fence is None:
                fence = f.group(1)
            elif f.group(1) == fence:
                fence = None
            continue
        if fence is not None:
            continue
        m = BOX.match(line.rstrip("\r"))
        if m:
            out.append((i, m.group(2) != " ", m.group(4).strip()))
    return out


def find_box(body, text):
    """The one checkbox containing TEXT, as (line index, ticked, text)."""
    if not text:
        raise SystemExit("--match: empty text")
    hits = [b for b in boxes(body) if text in b[2]]
    if not hits:
        raise SystemExit(f"no checkbox contains {text!r}")
    if len(hits) > 1:
        listed = "; ".join(repr(b[2]) for b in hits)
        raise SystemExit(
            f"{len(hits)} checkboxes contain {text!r}: {listed}; give more of the text"
        )
    return hits[0]


def ticked(body, text):
    """(new body, ticked box text, whether it was already ticked)."""
    idx, done, label = find_box(body, text)
    if done:
        return body, label, True
    lines = body.split("\n")
    line = lines[idx]
    m = BOX.match(line.rstrip("\r"))
    at = len(m.group(1)) + 1  # the space inside "[ ]"
    lines[idx] = line[:at] + "x" + line[at + 1 :]
    return "\n".join(lines), label, False


# --- commands ---------------------------------------------------------------


def issue(repo, n):
    got = gh_api("GET", f"repos/{ORG}/{repo}/issues/{n}")
    if "pull_request" in got:
        raise SystemExit(f"{repo}#{n} is a pull request, not an issue")
    return got


def send(dry, method, path, body):
    if dry:
        print(json.dumps({"method": method, "path": path, "body": body}, indent=2))
        return None
    return gh_api(method, path, body)


def cmd_criteria(a):
    repo, n = parse_ref(a.ref)
    got = issue(repo, n)
    items = [{"text": t, "ticked": d} for _, d, t in boxes(got.get("body"))]
    out = {
        "repo": f"{ORG}/{repo}",
        "number": n,
        "title": got["title"],
        "state": got["state"],
        "criteria": items,
        "open": sum(1 for i in items if not i["ticked"]),
    }
    print(json.dumps(out, indent=2))
    return 0


def cmd_tick(a):
    repo, n = parse_ref(a.ref)
    got = issue(repo, n)
    body, label, already = ticked(got.get("body") or "", a.match)
    if already:
        print(f"{repo}#{n}: already ticked: {label}")
        return 0
    send(a.dry_run, "PATCH", f"repos/{ORG}/{repo}/issues/{n}", {"body": body})
    print(f"{repo}#{n}: ticked: {label}")
    return 0


def cmd_close(a):
    repo, n = parse_ref(a.ref)
    with open(a.evidence, encoding="utf-8") as f:
        evidence = f.read().strip()
    if not evidence:
        raise SystemExit(f"{a.evidence}: empty evidence")
    got = issue(repo, n)
    if got["state"] != "open":
        raise SystemExit(f"{repo}#{n} is already {got['state']}")
    body = got.get("body") or ""
    labels = []
    for text in a.tick or []:  # every match checked before any write
        body, label, _ = ticked(body, text)
        labels.append(label)
    left = [t for _, d, t in boxes(body) if not d]
    if left and not a.partial:
        listed = "; ".join(repr(t) for t in left)
        raise SystemExit(
            f"{repo}#{n}: {len(left)} criteria unticked: {listed}; tick them or pass --partial"
        )
    if left:
        evidence += "\n\nClosed with criteria still open:\n" + "\n".join(f"- [ ] {t}" for t in left)
    if "Generated by [Claude Code]" not in evidence:
        evidence += FOOTER
    path = f"repos/{ORG}/{repo}/issues/{n}"
    send(a.dry_run, "POST", f"{path}/comments", {"body": evidence})
    if body != (got.get("body") or ""):
        send(a.dry_run, "PATCH", path, {"body": body})
    send(a.dry_run, "PATCH", path, {"state": "closed", "state_reason": "completed"})
    for label in labels:
        print(f"{repo}#{n}: ticked: {label}")
    print(f"{repo}#{n}: closed as completed" + (f", {len(left)} criteria open" if left else ""))
    return 0


# --- self-test --------------------------------------------------------------

BODY = """## Acceptance criteria

- [ ] script + self-test in CI, docs/tools.md row
- [ ] the orchestrator skill uses it
  * [X] a nested one, ticked
1. [ ] numbered [ ] with brackets and $HOME
- [ ]
- [x] already done

```
- [ ] inside a fence, never read
```
> - [ ] quoted, not a criterion
"""


class Fake:
    """A fake GitHub behind gh_api: one repository's issues and comments."""

    def __init__(self):
        self.issues = {
            1007: {"number": 1007, "title": "t", "state": "open", "body": BODY},
            1: {"number": 1, "title": "pr", "state": "open", "body": "", "pull_request": {}},
            2: {"number": 2, "title": "c", "state": "closed", "body": "- [ ] x"},
        }
        self.comments, self.writes = [], []

    def __call__(self, method, path, body=None):
        p = path.split("/")
        if p[:3] != ["repos", ORG, ".github"] or len(p) < 5 or p[3] != "issues":
            raise GhError(path, "Not Found (HTTP 404)")
        i = self.issues.get(int(p[4]))
        if i is None:
            raise GhError(path, "Not Found (HTTP 404)")
        if method != "GET":
            self.writes.append((method, path, body))
        if len(p) == 6 and p[5] == "comments" and method == "POST":
            self.comments.append(body["body"])
            return {"body": body["body"]}
        if len(p) == 5 and method == "PATCH":
            i.update(body)
        return dict(i)


def self_test():
    global gh_api
    fails = []

    def ok(cond, what):
        if not cond:
            fails.append(what)

    def expect_exit(fn, needle, what):
        try:
            fn()
            ok(False, what + ": accepted")
        except SystemExit as e:
            ok(needle in str(e), f"{what}: said {e}")

    got = boxes(BODY)
    ok(
        [(d, t) for _, d, t in got]
        == [
            (False, "script + self-test in CI, docs/tools.md row"),
            (False, "the orchestrator skill uses it"),
            (True, "a nested one, ticked"),
            (False, "numbered [ ] with brackets and $HOME"),
            (False, ""),
            (True, "already done"),
        ],
        f"boxes: {got}",
    )
    ok(parse_ref("swarm-routing/.github#7") == (".github", 7), "full ref")
    ok(parse_ref("AntHocNet#12") == ("AntHocNet", 12), "bare ref")
    expect_exit(lambda: parse_ref("evil/x#1"), "not a", "another owner")
    expect_exit(lambda: parse_ref(".github"), "not a", "no number")
    # brackets and $ in the text are literal: this line, and only it, changes
    new, label, _ = ticked(BODY, "[ ] with brackets and $HOME")
    ok(
        "1. [x] numbered [ ] with brackets and $HOME" in new
        and new.replace("1. [x] numbered", "1. [ ] numbered") == BODY,
        "tick by position, one line",
    )
    ok(ticked(BODY, "[ ]")[1].startswith("numbered"), "[ ] is text: one box contains it")
    expect_exit(lambda: ticked(BODY, "it"), "2 checkboxes contain", "a match in several")
    expect_exit(lambda: ticked(BODY, "inside a fence"), "no checkbox", "a fenced box")
    expect_exit(lambda: ticked(BODY, "quoted"), "no checkbox", "a quoted box")
    expect_exit(lambda: ticked(BODY, "s*"), "no checkbox", "a glob is not a pattern")
    expect_exit(lambda: ticked(BODY, ""), "empty", "empty text")
    ok(ticked(BODY, "already done")[2] is True, "already ticked")

    real, out = gh_api, sys.stdout
    tmp = tempfile.mkdtemp()
    ev, empty = os.path.join(tmp, "ev.md"), os.path.join(tmp, "empty.md")
    with open(ev, "w") as f:
        f.write("Done in #1010 (merge abc123).\n")
    with open(empty, "w") as f:
        f.write("  \n")
    try:
        sys.stdout = buf = _Buf()
        fake = gh_api = Fake()
        p = parser()
        ok(run(p, ["criteria", ".github#1007"]) == 0, "criteria")
        data = json.loads(buf.take())
        ok(data["open"] == 4 and len(data["criteria"]) == 6, f"criteria json: {data}")
        expect_exit(lambda: run(p, ["criteria", ".github#1"]), "pull request", "a PR")
        ok(run(p, ["tick", ".github#1007", "--match", "orchestrator skill"]) == 0, "tick")
        ok("- [x] the orchestrator skill uses it" in fake.issues[1007]["body"], "tick written")
        n = len(fake.writes)
        ok(run(p, ["tick", ".github#1007", "--match", "already"]) == 0, "tick again")
        ok(len(fake.writes) == n, "an already-ticked box is not written")
        ok(run(p, ["tick", ".github#1007", "--match", "self-test", "--dry-run"]) == 0, "dry tick")
        ok(len(fake.writes) == n and '"PATCH"' in buf.take(), "a dry run writes nothing")
        # close: refused before any write while a box stays open
        expect_exit(
            lambda: run(p, ["close", ".github#1007", "--evidence", ev, "--tick", "self-test"]),
            "2 criteria unticked",
            "close with open criteria",
        )
        ok(len(fake.writes) == n and not fake.comments, "a refused close writes nothing")
        expect_exit(
            lambda: run(p, ["close", ".github#1007", "--evidence", ev, "--tick", "nothing"]),
            "no checkbox",
            "close with a bad --tick",
        )
        expect_exit(
            lambda: run(p, ["close", ".github#1007", "--evidence", empty]), "empty", "no evidence"
        )
        expect_exit(lambda: run(p, ["close", ".github#2", "--evidence", ev]), "already", "closed")
        args = ["close", ".github#1007", "--evidence", ev]
        for t in ("self-test", "with brackets", "nested"):
            args += ["--tick", t]
        expect_exit(lambda: run(p, args), "1 criteria unticked: ''", "an empty box still counts")
        ok(run(p, args + ["--partial"]) == 0, "close --partial")
        c = fake.comments[-1]
        ok(
            c.startswith("Done in #1010")
            and "Closed with criteria still open:\n- [ ] " in c
            and c.endswith(FOOTER),
            f"evidence comment: {c!r}",
        )
        i = fake.issues[1007]
        ok(i["state"] == "closed" and i["state_reason"] == "completed", "closed as completed")
        ok(
            "- [x] script + self-test" in i["body"] and "1. [x] numbered [ ]" in i["body"],
            "ticked on close",
        )
        ok(
            [w[0] for w in fake.writes[n:]] == ["POST", "PATCH", "PATCH"],
            "comment, then ticks, then close",
        )
        # a full close: every box ticked, no --partial needed
        fake.issues[1007] = {"number": 1007, "title": "t", "state": "open", "body": "- [ ] a\n"}
        ok(run(p, ["close", ".github#1007", "--evidence", ev, "--tick", "a"]) == 0, "full close")
        ok("still open" not in fake.comments[-1], "no open list on a full close")
    finally:
        gh_api, sys.stdout = real, out
        shutil.rmtree(tmp, ignore_errors=True)
    if fails:
        for f in fails:
            print("FAIL:", f)
        return 1
    print("criteria.py self-test: ok")
    return 0


class _Buf:
    def __init__(self):
        self.parts = []

    def write(self, s):
        self.parts.append(s)

    def flush(self):
        pass

    def take(self):
        s, self.parts = "".join(self.parts), []
        return s


# --- main -------------------------------------------------------------------


def parser():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--self-test", action="store_true")
    sub = ap.add_subparsers(dest="cmd")
    c = sub.add_parser("criteria")
    c.add_argument("ref")
    t = sub.add_parser("tick")
    t.add_argument("ref")
    t.add_argument("--match", required=True)
    t.add_argument("--dry-run", action="store_true")
    cl = sub.add_parser("close")
    cl.add_argument("ref")
    cl.add_argument("--evidence", required=True)
    cl.add_argument("--tick", action="append")
    cl.add_argument("--partial", action="store_true")
    cl.add_argument("--dry-run", action="store_true")
    return ap


def run(ap, argv):
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    fn = {"criteria": cmd_criteria, "tick": cmd_tick, "close": cmd_close}.get(a.cmd)
    if fn is None:
        ap.print_help()
        return 2
    return fn(a)


def main(argv=None):
    return run(parser(), sys.argv[1:] if argv is None else argv)


if __name__ == "__main__":
    sys.exit(main())
