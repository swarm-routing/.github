"""List the org's epics where people and agents look for work.

Usage:
  epics.py fetch [--out FILE] [--repos A,B]       the data, as JSON (stdout by default)
  epics.py readme [REPO_DIR] [--repo NAME] [--check]  this repo's README section
  epics.py roadmap FILE [--check]                  every public repo's epics (ROADMAP.md)
  epics.py profile FILE [--check]                  the open epics (profile/README.md)
  epics.py check-all                               every public repo's README, read through the API
  epics.py --self-test

Every command but fetch and --self-test takes `--data FILE` to use saved data
instead of the GitHub API. `--repos A,B` reads only those repositories. Without
it the org's repositories are listed through `orgs/swarm-routing/repos`; where
that is forbidden (HTTP 403, as in a Claude Code cloud session, which is bound
to its repositories), the list falls back to the repositories named in this
repository's ROADMAP.md#epics, the last generated list (a repository created
since then is missing: name it with `--repos`). A line on stderr says which
source was used. The API is read through `gh api`, so it uses the caller's
`gh` login, or GH_TOKEN in a workflow.

An epic is an issue labelled `epic`. Its status is derived, never typed:
  Done         closed as completed
  Dropped      closed as not planned
  In progress  open, and at least one sub-issue closed (as done or not)
  Planned      open, no sub-issue closed yet
An epic is Done or Dropped only once the epic itself is closed; one whose
sub-issues are all closed stays In progress until someone closes it.
So the lists stay true as long as epics have their children linked as
sub-issues (CONTRIBUTING.md, Issues) and someone re-runs this script.

The section lives between `<!-- epics:begin -->` and `<!-- epics:end -->`.
`readme` inserts it before the `## Licence` heading (or at the end) the first
time; `roadmap` and `profile` need the markers in place. Private repositories
never appear. Output is a summary line per file (AntHocNet ADR-0014). Stdlib
only.
"""

import argparse
import base64
import json
import os
import re
import subprocess
import sys
import tempfile
from urllib.parse import quote

ORG = "swarm-routing"
GH = "https://github.com"
BEGIN = "<!-- epics:begin -->"
END = "<!-- epics:end -->"
GENERATED = (
    "<!-- Generated by swarm-routing/.github tools/epics/epics.py from the issues "
    "labelled `epic`; edit the issues, then re-run it. -->"
)
ROADMAP_URL = f"{GH}/{ORG}/.github/blob/main/ROADMAP.md#epics"
ISSUES_URL = f"{GH}/{ORG}/.github/blob/main/CONTRIBUTING.md#issues"
ORDER = {"In progress": 0, "Planned": 1}
ROADMAP = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "ROADMAP.md"
)


# --- data ---------------------------------------------------------------


class GhError(SystemExit):
    """A failed `gh api` call; `missing` is true for HTTP 404 only."""

    def __init__(self, path, stderr):
        super().__init__(f"gh api {path}: {stderr}")
        self.missing = "HTTP 404" in stderr
        self.forbidden = "HTTP 403" in stderr


def gh_api(path):
    r = subprocess.run(["gh", "api", path], capture_output=True, text=True)
    if r.returncode != 0:
        raise GhError(path, r.stderr.strip())
    return json.loads(r.stdout)


def gh_pages(path):
    out, page = [], 1
    while True:
        sep = "&" if "?" in path else "?"
        batch = gh_api(f"{path}{sep}per_page=100&page={page}")
        out += batch
        if len(batch) < 100:
            return out
        page += 1


def epic_of(issue):
    s = issue.get("sub_issues_summary") or {}
    return {
        "number": issue["number"],
        "title": issue["title"],
        "url": issue["html_url"],
        "state": issue["state"],
        "state_reason": issue.get("state_reason"),
        "closed_at": issue.get("closed_at"),
        "total": s.get("total", 0),
        "completed": s.get("completed", 0),
    }


def roadmap_repos(path=ROADMAP):
    """The repository names in the generated section of ROADMAP.md, in order."""
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return []
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        return []
    pat = rf"^### \[([^\]]+)\]\({re.escape(GH)}/{re.escape(ORG)}/[^)]+\)$"
    return re.findall(pat, text[i:j], re.M)


def listing_of(names, roadmap=ROADMAP):
    """The repositories to read and where their names came from (printed on
    stderr): `names`, else the org listing, else ROADMAP.md when that is 403."""
    if names:
        source = "--repos"
    else:
        try:
            listing = gh_pages(f"orgs/{ORG}/repos?type=public")
            print(f"epics: repositories from the org listing ({len(listing)})", file=sys.stderr)
            return listing
        except GhError as e:
            if not e.forbidden:
                raise
            names = roadmap_repos(roadmap)
            if not names:
                raise SystemExit(
                    f"epics: the org listing is forbidden (HTTP 403) and {roadmap} names no "
                    "repository; pass --repos A,B"
                ) from None
            source = (
                f"{os.path.basename(roadmap)}#epics, as the org listing is forbidden (HTTP 403)"
            )
    print(f"epics: repositories from {source} ({len(names)})", file=sys.stderr)
    return [gh_api(f"repos/{ORG}/{n}") for n in names]


def fetch(names=None, roadmap=ROADMAP):
    """Every public, non-archived repo of the org, or only `names` (still
    dropping private ones); see listing_of for where the list comes from."""
    listing = listing_of(names, roadmap)
    repos = []
    for r in listing:
        if r["private"] or r["archived"] or r["fork"]:
            continue
        issues = gh_pages(f"repos/{ORG}/{r['name']}/issues?labels=epic&state=all")
        epics = [epic_of(i) for i in issues if "pull_request" not in i]
        repos.append({"name": r["name"], "url": r["html_url"], "epics": epics})
    repos.sort(key=lambda r: (r["name"] != ".github", r["name"].lower()))
    return {"org": ORG, "repos": repos}


def load(args):
    if args.data:
        with open(args.data, encoding="utf-8") as f:
            return json.load(f)
    return fetch(args.repos)


# --- rendering ----------------------------------------------------------


def clean(title):
    """'[epic][protocol] ARA as …' and 'epic: …' -> the title alone."""
    t = re.sub(r"^\s*(\[[^\]]*\]\s*)+", "", title)
    t = re.sub(r"^\s*epic\s*:\s*", "", t, flags=re.I)
    return t.replace("|", "\\|").strip()


def status(e):
    if e["state"] == "closed":
        return "Dropped" if e.get("state_reason") == "not_planned" else "Done"
    return "In progress" if e["completed"] else "Planned"


def progress(e):
    return f"{e['completed']} / {e['total']}" if e["total"] else "no sub-issues yet"


def split(epics):
    live = sorted(
        (e for e in epics if e["state"] == "open"), key=lambda e: (ORDER[status(e)], e["number"])
    )
    done = sorted(
        (e for e in epics if e["state"] != "open"), key=lambda e: e["closed_at"] or "", reverse=True
    )
    return live, done


def link(e):
    return f"[#{e['number']}]({e['url']}) {clean(e['title'])}"


def live_table(live):
    rows = ["| Epic | Status | Sub-issues closed |", "|------|--------|-------------------|"]
    rows += [f"| {link(e)} | {status(e)} | {progress(e)} |" for e in live]
    return rows


def done_block(done):
    if not done:
        return []
    rows = [
        "",
        f"<details><summary>Closed: {len(done)} epic{'s' if len(done) != 1 else ''}</summary>",
        "",
    ]
    rows += ["| Epic | Closed |", "|------|--------|"]
    rows += [f"| {link(e)} | {status(e)} {(e['closed_at'] or '')[:10]} |" for e in done]
    return rows + ["", "</details>"]


def repo_body(repo):
    live, done = split(repo["epics"])
    if live:
        out = live_table(live)
    else:
        out = ["No open epic: the work here is tracked as single issues."]
    return out + done_block(done)


def readme_section(repo):
    q = quote("label:epic")
    lines = [
        BEGIN,
        GENERATED,
        "",
        f"What is planned and in progress here: the issues labelled "
        f"[`epic`]({repo['url']}/issues?q={q}). An epic's open sub-issues carry a "
        f"`priority:*` and a `model:*` label, so a contributor or an AI agent can pick "
        f"one up ([how issues work]({ISSUES_URL})). The whole org's plan: the "
        f"[roadmap]({ROADMAP_URL}).",
        "",
    ]
    return "\n".join(lines + repo_body(repo) + ["", END])


def roadmap_section(data):
    lines = [
        BEGIN,
        GENERATED,
        "",
        "Every epic of every public repository, open first. A status is derived "
        "from the issue: an open epic is **Planned** (no sub-issue closed) or "
        "**In progress** (at least one closed); it is **Done** or **Dropped** "
        "only once the epic itself is closed (as completed or as not planned). "
        "Each repository's README carries its own list.",
    ]
    for repo in data["repos"]:
        lines += ["", f"### [{repo['name']}]({repo['url']})", ""]
        lines += repo_body(repo)
    return "\n".join(lines + ["", END])


def profile_section(data):
    lines = [
        BEGIN,
        GENERATED,
        "",
        "| Repository | Epic | Status | Sub-issues closed |",
        "|------------|------|--------|-------------------|",
    ]
    n = 0
    for repo in data["repos"]:
        live, _ = split(repo["epics"])
        for e in live:
            lines.append(
                f"| [{repo['name']}]({repo['url']}) | {link(e)} | {status(e)} | {progress(e)} |"
            )
            n += 1
    if not n:
        lines = lines[:3] + ["No open epic."]
    return "\n".join(lines + ["", END])


# --- files --------------------------------------------------------------


def replace(text, section, insert):
    """Text with the marked section replaced; `insert` adds it when missing."""
    i, j = text.find(BEGIN), text.find(END)
    if i >= 0 and j > i:
        return text[:i] + section + text[j + len(END) :]
    if i >= 0 or j >= 0:
        raise SystemExit(f"unbalanced {BEGIN} / {END} markers")
    if not insert:
        raise SystemExit(f"no {BEGIN} / {END} markers to fill")
    block = f"## Epics\n\n{section}\n\n"
    m = re.search(r"^## Licen[cs]e\b", text, re.M)
    if m:
        return text[: m.start()] + block + text[m.start() :]
    return text.rstrip("\n") + "\n\n" + block.rstrip("\n") + "\n"


def write(path, section, check, insert):
    if not os.path.exists(path):
        raise SystemExit(f"{path}: missing (a README needs at least its title first)")
    with open(path, encoding="utf-8") as f:
        old = f.read()
    new = replace(old, section, insert)
    if new == old:
        print(f"{path}: up to date")
        return 0
    if check:
        print(f"{path}: stale (run epics.py to refresh)")
        return 1
    with open(path, "w", encoding="utf-8") as f:
        f.write(new)
    print(f"{path}: updated")
    return 0


def repo_name(repo_dir):
    """The GitHub name of a checkout, from its origin URL."""
    r = subprocess.run(
        ["git", "-C", repo_dir, "remote", "get-url", "origin"], capture_output=True, text=True
    )
    m = re.search(r"[/:]([^/:]+?)(?:\.git)?/?$", r.stdout.strip())
    if r.returncode != 0 or not m:
        raise SystemExit(f"{repo_dir}: cannot tell the repository name; pass --repo")
    return m.group(1)


def find(data, name):
    for repo in data["repos"]:
        if repo["name"].lower() == name.lower():
            return repo
    raise SystemExit(f"{name}: not a public {ORG} repository")


def check_all(data):
    stale = 0
    for repo in data["repos"]:
        want = readme_section(repo)
        try:
            raw = gh_api(f"repos/{ORG}/{repo['name']}/readme")
            text = base64.b64decode(raw["content"]).decode("utf-8")
        except GhError as e:
            if not e.missing:  # an outage or a token problem is not drift
                raise
            text = ""
        i, j = text.find(BEGIN), text.find(END)
        have = text[i : j + len(END)] if i >= 0 and j > i else None
        if have == want:
            print(f"{repo['name']}: up to date")
        else:
            stale += 1
            print(f"{repo['name']}: {'no epics section' if have is None else 'stale'}")
    return 1 if stale else 0


# --- self-test ----------------------------------------------------------


def fixture():
    def e(n, title, state="open", done=0, total=0, reason=None, closed=None):
        return {
            "number": n,
            "title": title,
            "url": f"{GH}/{ORG}/x/issues/{n}",
            "state": state,
            "state_reason": reason,
            "closed_at": closed,
            "total": total,
            "completed": done,
        }

    return {
        "org": ORG,
        "repos": [
            {
                "name": ".github",
                "url": f"{GH}/{ORG}/.github",
                "epics": [e(6, "epic: org template", done=3, total=26)],
            },
            {
                "name": "x",
                "url": f"{GH}/{ORG}/x",
                "epics": [
                    e(9, "[epic][bench] later | maybe", total=2),
                    e(3, "[epic][protocol] going", done=1, total=2),
                    e(1, "[epic] shipped", "closed", 4, 4, "completed", "2026-10-01T00:00:00Z"),
                    e(2, "[epic] abandoned", "closed", 0, 1, "not_planned", "2026-10-05T00:00:00Z"),
                ],
            },
            {"name": "y", "url": f"{GH}/{ORG}/y", "epics": []},
        ],
    }


def fallback_test(ok, data):
    """fetch through a fake `gh api`: the org listing, a 403 on it (the
    ROADMAP fallback), --repos, and a 403 with no ROADMAP list."""
    global gh_api
    real = gh_api
    calls = []

    def fake(forbid):
        def api(path):
            calls.append(path)
            if path.startswith(f"orgs/{ORG}/repos"):
                if forbid:
                    raise GhError(path, "gh: sessions are bound to their repositories (HTTP 403)")
                return [repo("x"), repo("y"), repo("papers", private=True)]
            if "/issues?" in path:
                return []
            return repo(path.split("/")[2])

        return api

    def repo(name, private=False):
        url = f"{GH}/{ORG}/{name}"
        return {"name": name, "html_url": url, "private": private, "archived": False, "fork": False}

    def names(got):
        return [r["name"] for r in got["repos"]]

    err, quiet = sys.stderr, open(os.devnull, "w")
    with tempfile.TemporaryDirectory() as d:
        roadmap = os.path.join(d, "ROADMAP.md")
        with open(roadmap, "w", encoding="utf-8") as f:
            f.write("# Roadmap\n\n## Epics\n\n" + roadmap_section(data) + "\n\n### [z](x)\n")
        ok(roadmap_repos(roadmap) == [".github", "x", "y"], "ROADMAP names, generated section only")
        sys.stderr = quiet
        try:
            gh_api = fake(False)
            ok(names(fetch(roadmap=roadmap)) == ["x", "y"], "org listing, private dropped")
            ok(f"repos/{ORG}/x" not in calls, "the listing needs no per-repository read")
            gh_api, calls[:] = fake(True), []
            got = names(fetch(roadmap=roadmap))
            ok(got == [".github", "x", "y"], "403 falls back to the ROADMAP list")
            ok(f"repos/{ORG}/.github" in calls, "fallback reads each repository")
            ok(names(fetch(["y"], roadmap=roadmap)) == ["y"], "--repos wins")
            try:
                fetch(roadmap=os.path.join(d, "none.md"))
                ok(False, "403 with no ROADMAP list accepted")
            except GhError:
                ok(False, "403 with no ROADMAP list raised the API error")
            except SystemExit as e:
                ok("--repos" in str(e), "403 with no ROADMAP list says to pass --repos")
        finally:
            gh_api, sys.stderr = real, err
            quiet.close()


def self_test():
    def ok(cond, what):
        if not cond:
            raise SystemExit(f"self-test FAILED: {what}")

    data = fixture()
    x = find(data, "X")
    ok(clean("[epic][bench] a | b") == "a \\| b", "title prefix and pipe")
    ok(clean("epic: org template") == "org template", "epic: prefix")
    s = readme_section(x)
    ok(s.startswith(BEGIN) and s.endswith(END), "markers")
    ok(s.index("#3") < s.index("#9"), "in progress before planned")
    ok("| In progress | 1 / 2 |" in s and "| Planned | 0 / 2 |" in s, "status and progress")
    ok("Closed: 2 epics" in s and s.index("#2") < s.index("#1]"), "done list, newest first")
    ok("Dropped 2026-10-05" in s, "not planned is dropped")
    ok("No open epic" in readme_section(find(data, "y")), "empty repo")
    p = profile_section(data)
    ok("#1]" not in p and "#3]" in p and "[.github]" in p, "profile lists open epics only")
    r = roadmap_section(data)
    ok(r.index("### [.github]") < r.index("### [x]") < r.index("### [y]"), "roadmap order")
    ok(GhError("x", "gh: Not Found (HTTP 404)").missing, "404 is a missing README")
    ok(not GhError("x", "gh: API rate limit exceeded (HTTP 403)").missing, "403 is an error")
    try:
        find(data, "papers")
        ok(False, "unknown repo accepted")
    except SystemExit:
        pass

    fallback_test(ok, data)

    with tempfile.TemporaryDirectory() as d:
        path = os.path.join(d, "README.md")
        with open(path, "w") as f:
            f.write("# x\n\nIntro.\n\n## Licence\n\nSee LICENSING.md.\n")
        quiet = open(os.devnull, "w")
        out, sys.stdout = sys.stdout, quiet
        try:
            ok(write(path, s, True, True) == 1, "check reports missing section")
            ok(write(path, s, False, True) == 0, "insert")
            text = open(path).read()
            ok(text.index("## Epics") < text.index("## Licence"), "inserted before the licence")
            ok(write(path, s, True, True) == 0, "idempotent")
            ok(write(path, readme_section(find(data, "y")), True, True) == 1, "check sees a change")
            with open(path, "w") as f:
                f.write("# x\n")
            write(path, s, False, True)
            ok(open(path).read().endswith(END + "\n"), "appended when there is no licence heading")
            with open(path, "w") as f:
                f.write("# x\n" + BEGIN + "\n")
            try:
                write(path, s, False, True)
                ok(False, "unbalanced markers accepted")
            except SystemExit:
                pass
        finally:
            sys.stdout = out
            quiet.close()
    print("epics.py self-test: ok")
    return 0


# --- main ---------------------------------------------------------------


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--self-test", action="store_true")
    sub = ap.add_subparsers(dest="cmd")
    repos = argparse.ArgumentParser(add_help=False)
    repos.add_argument("--repos", type=lambda v: [n for n in v.split(",") if n])
    f = sub.add_parser("fetch", parents=[repos])
    f.add_argument("--out")
    for name in ("readme", "roadmap", "profile", "check-all"):
        p = sub.add_parser(name, parents=[repos])
        p.add_argument("--data")
        if name == "readme":
            p.add_argument("repo_dir", nargs="?", default=".")
            p.add_argument("--repo")
        elif name != "check-all":
            p.add_argument("file")
        if name != "check-all":
            p.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    if args.self_test:
        return self_test()
    if args.cmd == "fetch":
        text = json.dumps(fetch(args.repos), indent=1, sort_keys=True) + "\n"
        if args.out:
            with open(args.out, "w", encoding="utf-8") as fh:
                fh.write(text)
            print(f"{args.out}: written")
        else:
            sys.stdout.write(text)
        return 0
    if args.cmd is None:
        ap.print_help()
        return 2
    data = load(args)
    if args.cmd == "readme":
        repo = find(data, args.repo or repo_name(args.repo_dir))
        return write(
            os.path.join(args.repo_dir, "README.md"), readme_section(repo), args.check, True
        )
    if args.cmd == "roadmap":
        return write(args.file, roadmap_section(data), args.check, False)
    if args.cmd == "profile":
        return write(args.file, profile_section(data), args.check, False)
    return check_all(data)


if __name__ == "__main__":
    sys.exit(main())
