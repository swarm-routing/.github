def parser():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--self-test", action="store_true")
    sub = ap.add_subparsers(dest="cmd")
    o = sub.add_parser("open")
    o.add_argument("--repo", required=True)
    o.add_argument("id")
    o.add_argument("title")
    o.add_argument("--kind", choices=sorted(FORMS))
    o.add_argument("--field", action="append")
    o.add_argument("--priority", choices=["P1", "P2", "P3"], default="P2")
    o.add_argument(
        "--model",
        choices=["model:opus-5.5", "model:sonnet-5.5", "model:haiku-5.5"],
        default="model:opus-5.5",
    )
    o.add_argument("--dry-run", action="store_true")
    lg = sub.add_parser("log")
    lg.add_argument("--repo", required=True)
    lg.add_argument("id")
    lg.add_argument("--step", required=True)
    lg.add_argument("--text", required=True)
    for k in ("--versions", "--command", "--result"):
        lg.add_argument(k)
    lg.add_argument("--dry-run", action="store_true")
    s = sub.add_parser("steps")
    s.add_argument("--repo", required=True)
    s.add_argument("id")
    d = sub.add_parser("doc")
    d.add_argument("--repo")
    d.add_argument("id")
    return ap


def run(ap, argv):
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    fn = {"open": cmd_open, "log": cmd_log, "steps": cmd_steps, "doc": cmd_doc}.get(a.cmd)
    if fn is None:
        ap.print_help()
        return 2
    return fn(a)


def main(argv=None):
    return run(parser(), sys.argv[1:] if argv is None else argv)


if __name__ == "__main__":
    sys.exit(main())
