"""Keep one AI-files findings issue per org repository current.

Usage:
  ai_files_review.py run [--repos A,B] [--dry-run] [--offline]
  ai_files_review.py --self-test

For each public, non-archived, non-fork org repository (#143):
1. clone it shallowly and run check_docs.py's AI-files pass on it (#142),
   online unless --offline, so closed issues written as open are found;
2. keep one open issue in that repository titled
   `[docs] AI files: N finding(s)` (label `documentation`):
   - findings and no issue: open one;
   - findings and an issue: update its title and body in place when they
     changed (nothing when they did not);
   - no findings and an issue: close it as completed, with a comment.

Private repositories (papers) are never listed, so no issue is ever opened in
one and their findings never reach a log. The token comes from AI_FILES_TOKEN
(the org bot's: the GitHub App's installation token, else ORG_BOT_TOKEN), never
from the command line; it needs Issues: read and write on every repository.
Without it, or with --dry-run, nothing is written: one line per repository says
what would happen. Output is one line per repository (AntHocNet ADR-0014).
Stdlib only.
"""

import argparse
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ORG = "swarm-routing"
PREFIX = "[docs] AI files:"
LABELS = ["documentation", "model:haiku-4.5", "priority:P3"]
FOOTER = "\n\n---\n_Generated by the weekly `ai-files-review` workflow (swarm-routing/.github)._"


def load_check_docs():
    spec = importlib.util.spec_from_file_location("check_docs", os.path.join(HERE, "check_docs.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class Failure(SystemExit):
    pass


class GitHub:
    """GitHub through `gh api`; the token, when set, is in the environment only."""

    def __init__(self, token=None):
        self.env = dict(os.environ)
        if token:
            self.env["GH_TOKEN"] = token

    def api(self, method, path, body=None, paginate=False):
        cmd = ["gh", "api", "-X", method, path] + (["--paginate"] if paginate else [])
        if body is not None:
            cmd += ["--input", "-"]
        r = subprocess.run(
            cmd,
            input=json.dumps(body) if body is not None else None,
            capture_output=True,
            text=True,
            env=self.env,
        )
        if r.returncode != 0:
            raise Failure(f"gh api {method} {path}: {r.stderr.strip()}")
        out = r.stdout.strip()
        if paginate and out.startswith("[") and "]\n[" in out:
            out = "[" + out[1:-1].replace("]\n[", ",") + "]"
        return json.loads(out) if out else {}


def public_repos(gh, names=None):
    """Every public, non-archived, non-fork repository; with `names`, those read one by one
    (still dropping private ones) where the org listing is not reachable."""
    if names:
        listing = [gh.api("GET", f"repos/{ORG}/{n}") for n in names]
    else:
        listing = gh.api("GET", f"orgs/{ORG}/repos?type=public&per_page=100", paginate=True)
    names = [r["name"] for r in listing if not (r["private"] or r["archived"] or r["fork"])]
    return sorted(names, key=lambda n: (n != ".github", n.lower()))


def findings(check_docs, clone, online):
    """The AI-files WARN items of one repository, one string each."""
    rep = check_docs.Report()
    check_docs.check_ai_facts(clone, rep, online=online)
    out = []
    for row in rep.rows:
        if row["level"] == "WARN":
            out += [f"{row['msg']}: {i}" for i in row["items"]]
    return out


def title_for(items):
    return f"{PREFIX} {len(items)} finding(s)"


def body_for(repo, items, run_url):
    lines = [
        "## Context",
        "",
        f"The AI-files pass of `check_docs.py` (swarm-routing/.github#142) found facts in "
        f"`{repo}`'s AGENTS.md, CLAUDE.md or CONTEXT.md that no longer hold"
        + (f" ([run]({run_url}))." if run_url else "."),
        "",
        "## Findings",
        "",
        *[f"- [ ] {i}" for i in items],
        "",
        "## Scope",
        "",
        "Fix the hand-written sections in one PR, `docs(agents): fix stale facts in the ai "
        "files`; a managed section changes only through swarm-routing/.github `templates/`. "
        "A contradiction that needs a maintainer decision is recorded here, not changed. "
        "Reproduce with `python3 -I ../.github/tools/docs-review/check_docs.py . --online`.",
        "",
        "This issue is updated in place by the weekly run and closed when the repository is clean.",
    ]
    return "\n".join(lines) + FOOTER


def sync(gh, repo, items, dry_run, run_url):
    """Open, update or close `repo`'s findings issue; returns the action taken."""
    issues = gh.api(
        "GET", f"repos/{ORG}/{repo}/issues?state=open&labels=documentation&per_page=100"
    )
    mine = [i for i in issues if i["title"].startswith(PREFIX) and "pull_request" not in i]
    issue = mine[0] if mine else None
    if not items:
        if not issue:
            return "clean"
        if not dry_run:
            gh.api(
                "POST",
                f"repos/{ORG}/{repo}/issues/{issue['number']}/comments",
                {
                    "body": "Clean: the AI-files pass finds nothing any more"
                    + (f" ({run_url})" if run_url else "")
                    + "."
                    + FOOTER
                },
            )
            gh.api(
                "PATCH",
                f"repos/{ORG}/{repo}/issues/{issue['number']}",
                {"state": "closed", "state_reason": "completed"},
            )
        return f"close #{issue['number']}"
    title, body = title_for(items), body_for(repo, items, run_url)
    if not issue:
        if not dry_run:
            n = gh.api(
                "POST",
                f"repos/{ORG}/{repo}/issues",
                {"title": title, "body": body, "labels": LABELS},
            ).get("number")
            return f"open #{n}"
        return "open"
    # the run link changes every week; only the findings decide an update
    if issue["title"] == title and _same_findings(issue.get("body") or "", items):
        return f"unchanged #{issue['number']}"
    if not dry_run:
        gh.api(
            "PATCH",
            f"repos/{ORG}/{repo}/issues/{issue['number']}",
            {"title": title, "body": body},
        )
    return f"update #{issue['number']}"


def _same_findings(body, items):
    listed = [x[6:] for x in body.splitlines() if x.startswith(("- [ ] ", "- [x] "))]
    return listed == items


def run(args, gh=None, clone_url=None):
    token = os.environ.get("AI_FILES_TOKEN") or None
    dry_run = args.dry_run or not token
    if not token and not args.dry_run:
        print("ai-files-review: AI_FILES_TOKEN is not set; dry run")
    gh = gh or GitHub(token)
    clone_url = clone_url or "https://github.com/{org}/{repo}.git"
    run_url = ""
    if os.environ.get("GITHUB_RUN_ID"):
        run_url = (
            f"{os.environ.get('GITHUB_SERVER_URL', 'https://github.com')}/"
            f"{os.environ.get('GITHUB_REPOSITORY')}/actions/runs/{os.environ['GITHUB_RUN_ID']}"
        )
    wanted = [n.strip() for n in args.repos.split(",") if n.strip()]
    repos = public_repos(gh, wanted)
    if wanted:
        unknown = sorted(set(wanted) - set(repos))
        if unknown:
            raise Failure(f"ai-files-review: not a public org repository: {', '.join(unknown)}")
        repos = [r for r in repos if r in wanted]
    check_docs = load_check_docs()
    work = tempfile.mkdtemp(prefix="ai-files-")
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0")
    results, failed = [], []
    try:
        for repo in repos:
            clone = os.path.join(work, repo)
            r = subprocess.run(
                ["git", "clone", "-q", "--depth", "1", clone_url.format(org=ORG, repo=repo), clone],
                capture_output=True,
                text=True,
                env=env,
            )
            try:
                if r.returncode:
                    raise Failure(f"clone: {r.stderr.strip()}")
                items = findings(check_docs, clone, online=not args.offline)
                action = sync(gh, repo, items, dry_run, run_url)
            except Exception as e:  # noqa: BLE001 - one broken repository must not stop the rest
                failed.append(repo)
                print(f"{repo}: FAILED: {type(e).__name__}: {e}")
                continue
            verb = "would " if dry_run and action.split()[0] in ("open", "update", "close") else ""
            print(f"{repo}: {len(items)} finding(s); {verb}{action}")
            for i in items:
                print(f"    {i}")
            results.append((repo, len(items), action))
    finally:
        shutil.rmtree(work, ignore_errors=True)
    if failed:
        raise Failure(f"ai-files-review: {len(failed)} repositories failed: {', '.join(failed)}")
    return results


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--self-test", action="store_true")
    sub = p.add_subparsers(dest="cmd")
    r = sub.add_parser("run")
    r.add_argument("--repos", default="", help="comma-separated names (default: every public repo)")
    r.add_argument("--dry-run", action="store_true")
    r.add_argument("--offline", action="store_true", help="skip the issue-state rule (no gh reads)")
    args = p.parse_args(argv)
    if args.self_test:
        return self_test()
    if args.cmd != "run":
        p.error("a command is required")
    run(args)
    return 0


# --- self-test: local bare repositories and a recording fake GitHub ----------


def self_test():
    import contextlib
    import io

    failures = []

    def check(name, cond):
        if not cond:
            failures.append(name)

    work = tempfile.mkdtemp(prefix="ai-files-test-")
    remotes = os.path.join(work, "remotes")
    genv = dict(
        os.environ,
        GIT_AUTHOR_NAME="t",
        GIT_AUTHOR_EMAIL="t@example.org",
        GIT_COMMITTER_NAME="t",
        GIT_COMMITTER_EMAIL="t@example.org",
    )

    def make_repo(name, agents, extra=None):
        src = os.path.join(work, "src", name)
        os.makedirs(os.path.join(src, "core"))
        for rel, text in {"AGENTS.md": agents, "core/a.cc": "x\n", **(extra or {})}.items():
            os.makedirs(os.path.dirname(os.path.join(src, rel)), exist_ok=True)
            with open(os.path.join(src, rel), "w") as fh:
                fh.write(text)
        for cmd in (
            ["git", "init", "-q", "-b", "main", src],
            ["git", "-C", src, "add", "-A"],
            ["git", "-C", src, "commit", "-q", "-m", "init"],
            ["git", "clone", "-q", "--bare", src, os.path.join(remotes, ORG, name + ".git")],
        ):
            subprocess.run(cmd, check=True, capture_output=True, env=genv)

    make_repo("stale", "# AGENTS\n\nRun `core/gone.cc` and `tools/x.py`.\n")
    make_repo("clean", "# AGENTS\n\nRead `core/a.cc`.\n")
    make_repo("fixed", "# AGENTS\n\nRead `core/a.cc`.\n")
    make_repo("broken", "# AGENTS\n\nRead `core/a.cc`.\n", {".github/org-sync.toml": "[settings\n"})
    clone_url = "file://" + remotes + "/{org}/{repo}.git"

    class FakeGitHub:
        env = dict(os.environ)

        def __init__(self, issues):
            self.calls, self.issues = [], issues

        def api(self, method, path, body=None, paginate=False):
            self.calls.append((method, path, body))

            def meta(n):
                return {"name": n, "private": n == "papers", "archived": False, "fork": False}

            if path.startswith(f"orgs/{ORG}/repos"):
                return [meta(n) for n in ("stale", "clean", "fixed", "papers")]
            if method == "GET" and path.count("/") == 2:
                return meta(path.split("/")[2])
            if method == "GET" and "/issues?" in path:
                repo = path.split("/")[2]
                return self.issues.get(repo, [])
            if method == "POST" and path.endswith("/issues"):
                return {"number": 7}
            return {}

    def go(gh, dry=False, token="tok", repos=""):
        ns = argparse.Namespace(repos=repos, dry_run=dry, offline=True)
        old = os.environ.get("AI_FILES_TOKEN")
        if token:
            os.environ["AI_FILES_TOKEN"] = token
        else:
            os.environ.pop("AI_FILES_TOKEN", None)
        out = io.StringIO()
        try:
            with contextlib.redirect_stdout(out):
                res = run(ns, gh=gh, clone_url=clone_url)
        finally:
            if old is None:
                os.environ.pop("AI_FILES_TOKEN", None)
            else:
                os.environ["AI_FILES_TOKEN"] = old
        return res, out.getvalue()

    def writes(gh):
        return [c for c in gh.calls if c[0] != "GET"]

    old_issue = {"number": 3, "title": f"{PREFIX} 1 finding(s)", "body": "- [ ] old"}
    # dry run without a token: what would happen, no write
    gh = FakeGitHub({"fixed": [old_issue]})
    res, out = go(gh, token=None)
    check("no token: dry run", "AI_FILES_TOKEN is not set" in out and not writes(gh))
    check("dry run: would open", "stale: 2 finding(s); would open" in out)
    check("dry run: would close", "fixed: 0 finding(s); would close #3" in out)
    check("a private repository is never reviewed", "papers" not in out)

    # with a token: open, close, leave a clean one alone
    gh = FakeGitHub({"fixed": [old_issue]})
    res, out = go(gh)
    posts = [c for c in writes(gh) if c[0] == "POST" and c[1].endswith("/stale/issues")]
    check("findings and no issue: one opened", len(posts) == 1)
    check(
        "the issue is titled with the count and labelled documentation",
        posts
        and posts[0][2]["title"] == f"{PREFIX} 2 finding(s)"
        and "documentation" in posts[0][2]["labels"],
    )
    check(
        "the body lists each finding",
        posts and "core/gone.cc" in posts[0][2]["body"] and "tools/x.py" in posts[0][2]["body"],
    )
    closes = [c for c in writes(gh) if c[0] == "PATCH" and c[1].endswith("/fixed/issues/3")]
    check("clean and an issue: closed as completed", closes and closes[0][2]["state"] == "closed")
    check("a clean repo with no issue: no write", not [c for c in writes(gh) if "/clean/" in c[1]])
    check("no write to a private repository", not [c for c in gh.calls if "/papers/" in c[1]])

    # an issue with the same findings is left alone; changed findings update it in place
    items = [
        "paths that do not exist (fix them, or mark them planned): AGENTS.md:3: `core/gone.cc`"
    ]
    same = {
        "number": 5,
        "title": f"{PREFIX} 2 finding(s)",
        "body": body_for("stale", [items[0], items[0].replace("core/gone.cc", "tools/x.py")], "x"),
    }
    gh = FakeGitHub({"stale": [same]})
    res, out = go(gh, repos="stale")
    check("same findings: unchanged", "unchanged #5" in out and not writes(gh))
    changed = dict(same, body=body_for("stale", items, ""), title=f"{PREFIX} 1 finding(s)")
    gh = FakeGitHub({"stale": [changed]})
    res, out = go(gh, repos="stale")
    upd = [c for c in writes(gh) if c[0] == "PATCH"]
    check(
        "changed findings: updated in place",
        len(upd) == 1 and upd[0][2]["title"] == f"{PREFIX} 2 finding(s)" and "update #5" in out,
    )
    check("--repos limits the run", out.count("finding(s);") == 1)
    try:
        go(FakeGitHub({}), repos="papers")
        check("a private repository cannot be named", False)
    except Failure:
        pass

    try:
        go(FakeGitHub({}), repos="broken,clean")
        check("a broken repository fails the run", False)
    except Failure as e:
        check("…after reviewing the others", "1 repositories failed: broken" in str(e))

    shutil.rmtree(work, ignore_errors=True)
    for f in failures:
        print(f"FAIL: {f}")
    print(f"ai_files_review.py self-test: {'ok' if not failures else f'{len(failures)} failed'}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
