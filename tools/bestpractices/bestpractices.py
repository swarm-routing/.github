class Remote:
    """The network: bestpractices.dev's public JSON, and GitHub through `gh api`."""

    def __init__(self, token=None):
        self.env = dict(os.environ)
        if token:
            self.env["GH_TOKEN"] = token
        self.last = 0.0

    def _get(self, url):
        # the site asks for at most one request a second (BadgeApp docs/api.md)
        time.sleep(max(0.0, self.last + SITE_INTERVAL - time.monotonic()))
        req = urllib.request.Request(url, headers={"User-Agent": "bestpractices-check"})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return json.load(resp)
        finally:
            self.last = time.monotonic()

    def site(self, project):
        return self._get(f"{SITE}/projects/{project}.json")

    def search(self, repo_url):
        """The projects whose repo or home page URL is exactly repo_url (read-only, no login)."""
        return self._get(f"{SITE}/projects.json?url=" + urllib.parse.quote(repo_url, safe=""))

    def api(self, method, path, body=None, paginate=False):
        cmd = ["gh", "api", "-X", method, path] + (["--paginate"] if paginate else [])
        if body is not None:
            cmd += ["--input", "-"]
        r = subprocess.run(
            cmd,
            input=json.dumps(body) if body is not None else None,
            capture_output=True,
            text=True,
            env=self.env,
        )
        if r.returncode != 0:
            if "HTTP 404" in r.stderr:
                return None
            raise Failure(f"gh api {method} {path}: {r.stderr.strip()}")
        out = r.stdout.strip()
        if paginate and out.startswith("[") and "]\n[" in out:
            out = "[" + out[1:-1].replace("]\n[", ",") + "]"
        return json.loads(out) if out else {}

    def file(self, repo, path):
        got = self.api("GET", f"repos/{ORG}/{repo}/contents/{path}?ref=main")
        if not got or "content" not in got:
            return None
        import base64

        return base64.b64decode(got["content"]).decode("utf-8", "replace")

    def tree(self, repo):
        got = self.api("GET", f"repos/{ORG}/{repo}/git/trees/main?recursive=1") or {}
        return {t["path"] for t in got.get("tree", [])}

    def repos(self):
        listing = self.api("GET", f"orgs/{ORG}/repos?type=public&per_page=100", paginate=True) or []
        return sorted(r["name"] for r in listing if not (r["archived"] or r["private"]))


def registered(remote, slug):
    """The project id bestpractices.dev holds for https://github.com/<slug>, else ''."""
    url = f"https://github.com/{slug}"
    hits = [
        h
        for h in remote.search(url) or []
        if str(h.get("repo_url", "")).rstrip("/").lower() == url.lower()
    ]
    return str(min(h["id"] for h in hits)) if hits else ""


def project_of(remote, repo):
    text = remote.file(repo, CONFIG)
    if not text:
        return ""
    try:
        p = str(tomllib.loads(text).get("bestpractices_project", "")).strip()
    except tomllib.TOMLDecodeError:
        return ""
    return p if p.isdigit() else ""


def targets(remote, spec):
    """[(repo, project id, configured)]: --repos entries (NAME=ID or NAME), else every
    public org repository. A repository whose config names no project is looked up on the
    site by its URL: registered there, it is checked and its missing key is a finding."""
    out, failed = [], []
    names = [s.strip() for s in spec.split(",") if s.strip()] if spec else None
    for entry in names if names is not None else remote.repos():
        repo, _, given = entry.partition("=")
        try:
            configured = project_of(remote, repo)
            pid = given.strip() or configured or registered(remote, f"{ORG}/{repo}")
        except (urllib.error.URLError, OSError, ValueError, TypeError, KeyError, Failure) as e:
            failed.append(f"{repo}: FAILED: the lookup: {type(e).__name__}: {e}")
            continue
        if pid.isdigit():
            out.append((repo, pid, bool(configured)))
        elif names is not None:
            failed.append(
                f"{repo}: FAILED: no bestpractices_project in {CONFIG}, "
                "and not registered on bestpractices.dev"
            )
    return out, failed


URL_IN = re.compile(r"https://github\.com/([\w.-]+)/([\w.-]+)/(?:blob|tree)/main/([^\s<>)\"'#?]+)")


def findings(repo, data, proposed, tree):
    """(info lines, finding lines) for one project."""
    info = [f"level {data.get('badge_level', '?')}, passing {data.get('badge_percentage_0', '?')}%"]
    out = []
    unanswered = 0
    for c in PASSING:
        want = proposed.get(f"{c}_status")
        have = data.get(f"{c}_status")
        if not want or want in ("?", "unknown"):
            continue
        if have in (None, "?", "unknown"):
            unanswered += 1
        elif have != want:
            out.append(f"{c}: the site says {have}, {OUT} says {want}")
    if proposed:
        info.append(f"{unanswered} criteria {OUT} answers are not answered on the site yet")
    else:
        info.append(f"no {OUT} on main")
    for c in PASSING:
        why = data.get(f"{c}_justification") or ""
        for owner, name, path in URL_IN.findall(why):
            path = path.rstrip(".,;:")
            if (owner, name) != (ORG, repo) or path in tree:
                continue
            if any(t.startswith(path.rstrip("/") + "/") for t in tree):
                continue
            out.append(f"{c}: the justification points at {path}, not on main")
    for level in LEVELS:
        lost, won = data.get(f"lost_{level}_at"), data.get(f"achieved_{level}_at")
        if lost and (not won or lost > won):
            out.append(f"level lost: {level} since {lost[:10]}")
    return info, sorted(set(out), key=out.index)


def title_for(items):
    return f"{PREFIX} {len(items)} finding(s)"


def body_for(repo, project, items, run_url):
    lines = [
        "## Context",
        "",
        f"The weekly `bestpractices` check (swarm-routing/.github `tools/bestpractices/`) "
        f"found `{repo}`'s OpenSSF Best Practices entry ({SITE}/projects/{project}) out of "
        f"step with the repository" + (f" ([run]({run_url}))." if run_url else "."),
        "",
        "## Findings",
        "",
        *[f"- [ ] {i}" for i in items],
        "",
        "## Scope",
        "",
        f"bestpractices.dev has no write API, so a person fixes each one, logged in at "
        f"{SITE}/projects/{project}/passing: correct the answer, or regenerate `{OUT}` "
        f"(`python3 -I ../.github/tools/bestpractices/bestpractices.py answers . --write`) and "
        'press "Save (and continue)" with the robot; a justification pointing at a moved '
        "file gets the new URL. A lost level is answered on the site first.",
        "",
        "This issue is updated in place by the weekly run and closed when the entry is clean.",
    ]
    return "\n".join(lines) + FOOTER


def _same_findings(body, items):
    return [x[6:] for x in body.splitlines() if x.startswith(("- [ ] ", "- [x] "))] == items


def sync_issue(gh, repo, project, items, dry_run, run_url):
    issues = (
        gh.api(
            "GET", f"repos/{ORG}/{repo}/issues?state=open&labels=chore&per_page=100", paginate=True
        )
        or []
    )
    mine = [i for i in issues if i["title"].startswith(PREFIX) and "pull_request" not in i]
    issue = mine[0] if mine else None
    if not items:
        if not issue:
            return "clean"
        if not dry_run:
            note = "Clean: the bestpractices check finds nothing any more"
            gh.api(
                "POST",
                f"repos/{ORG}/{repo}/issues/{issue['number']}/comments",
                {"body": note + (f" ({run_url})" if run_url else "") + "." + FOOTER},
            )
            gh.api(
                "PATCH",
                f"repos/{ORG}/{repo}/issues/{issue['number']}",
                {"state": "closed", "state_reason": "completed"},
            )
        return f"close #{issue['number']}"
    title, body = title_for(items), body_for(repo, project, items, run_url)
    if not issue:
        if dry_run:
            return "open"
        n = gh.api(
            "POST", f"repos/{ORG}/{repo}/issues", {"title": title, "body": body, "labels": LABELS}
        ).get("number")
        return f"open #{n}"
    if issue["title"] == title and _same_findings(issue.get("body") or "", items):
        return f"unchanged #{issue['number']}"
    if not dry_run:
        gh.api(
            "PATCH", f"repos/{ORG}/{repo}/issues/{issue['number']}", {"title": title, "body": body}
        )
    return f"update #{issue['number']}"


def check(args, remote=None, gh=None):
    """Returns the exit code: 0 clean, 1 drift, 2 a project could not be read."""
    remote = remote or Remote()
    token = os.environ.get("BESTPRACTICES_TOKEN") or None
    dry_run = args.dry_run or not token
    if args.issues:
        if not token and not args.dry_run:
            print("bestpractices: BESTPRACTICES_TOKEN is not set; issues: dry run")
        gh = gh or Remote(token)
    run_url = ""
    if os.environ.get("GITHUB_RUN_ID"):
        run_url = (
            f"{os.environ.get('GITHUB_SERVER_URL', 'https://github.com')}/"
            f"{os.environ.get('GITHUB_REPOSITORY')}/actions/runs/{os.environ['GITHUB_RUN_ID']}"
        )
    todo, failed = targets(remote, args.repos)
    for line in failed:  # a lookup that failed, or a named repository on no project: not drift
        print(line)
    if not todo and not failed:
        print(f"bestpractices: no repository names bestpractices_project in {CONFIG}")
        return 0
    drift, broken = 0, len(failed)
    for repo, project, configured in todo:
        try:
            data = remote.site(project)
            text = remote.file(repo, OUT)
            proposed = json.loads(text) if text else {}
            if not isinstance(data, dict) or not isinstance(proposed, dict):
                raise ValueError(
                    f"not a JSON object: {'the site' if not isinstance(data, dict) else OUT}"
                )
            tree = remote.tree(repo)
        except (urllib.error.URLError, OSError, ValueError, Failure) as e:
            broken += 1
            print(f"{repo} (project {project}): FAILED: {type(e).__name__}: {e}")
            continue
        if (
            str(data.get("repo_url") or "").rstrip("/").lower()
            != f"https://github.com/{ORG}/{repo}".lower()
        ):
            broken += 1
            print(
                f"{repo} (project {project}): FAILED: the project's repo_url is {data.get('repo_url')}"
            )
            continue
        info, items = findings(repo, data, proposed, tree)
        if not configured:
            items.insert(
                0,
                f"registered as project {project}, but {CONFIG} has no "
                f'bestpractices_project = "{project}"',
            )
        drift += bool(items)
        action = ""
        if args.issues:
            try:
                action = sync_issue(gh, repo, project, items, dry_run, run_url)
                verb = (
                    "would " if dry_run and action.split()[0] in ("open", "update", "close") else ""
                )
                action = f"; issue: {verb}{action}"
            except (Failure, OSError, ValueError, KeyError) as e:
                broken += 1
                action = f"; issue: FAILED: {type(e).__name__}: {e}"
        print(f"{repo} (project {project}): {'; '.join(info)}; {len(items)} finding(s){action}")
        for i in items:
            print(f"    {i}")
    print(f"bestpractices: {len(todo)} project(s), {drift} drifting, {broken} unreadable")
    return 2 if broken else (1 if drift else 0)


