"""OpenSSF Best Practices (bestpractices.dev): answers, registration link, drift check.

Usage:
  bestpractices.py answers REPO_DIR [--slug OWNER/NAME] [--write] [--today YYYY-MM-DD]
  bestpractices.py register OWNER/NAME [--dir REPO_DIR] [--today YYYY-MM-DD]
  bestpractices.py check [--repos NAME[=ID],...] [--issues] [--dry-run]
  bestpractices.py --self-test

bestpractices.dev has no token write API: every answer is saved by a person
logged in to the site. This tool never logs in and never submits anything. It
does three things around that (swarm-routing/.github#23, swarm-routing/AntHocNet#790):

- `answers` derives the passing-level answers from what is in the repository
  (README, CONTRIBUTING, SECURITY.md, the licence files, CHANGELOG, the build
  files, the workflows: CI on pull requests, CodeQL, sanitizers, fuzzing,
  warnings) as `<criterion>_status` / `<criterion>_justification`, each
  justification naming the evidence by its full https URL on `main`. It prints
  the `.bestpractices.json` the site reads (`--write` writes it at the
  repository's top level); the site proposes those answers when the
  maintainer presses "Save (and continue)" with the robot. Criteria only the
  owner can answer (OWNER_ONLY) are always `?`, which the site ignores, as is
  any criterion the repository gives no evidence for. The crypto criteria are
  N/A (no cryptography) unless `.github/org-sync.toml` sets
  `bestpractices_crypto = true` or the sources call a crypto library; then
  they are `?` for the owner. A summary goes to stderr.
- `register` first asks the site, read-only, whether the repository is
  registered (`/projects.json?url=<repo_url>`, BadgeApp docs/api.md); if it
  is, it prints the project id, the `bestpractices_project = "<id>"` line
  for the repository's `.github/org-sync.toml`, and the site's
  automation-proposal links for that project
  (`/en/projects/<id>/passing/edit?<criterion>_status=..&..._justification=..`),
  split into links under 6000 characters, owner-only criteria left out; the
  answers come from --answers FILE, else the checkout's `.bestpractices.json`,
  else are derived. Opening a link changes nothing until the logged-in
  maintainer saves. Otherwise it says where to register (/en/projects/new):
  the site has no pre-filled registration form (`/en/projects?as=edit` only
  redirects for a project that exists), so the maintainer registers it, then
  runs `register` again for the proposal links.
- `check` reads each registered project's public JSON
  (https://www.bestpractices.dev/projects/<id>.json) for every org repository
  whose `.github/org-sync.toml` names `bestpractices_project` (or --repos,
  where NAME=ID gives the id directly) and reports, one block per repository
  (AntHocNet ADR-0014): a repository registered on the site whose config
  names no `bestpractices_project` (every public org repository without the
  key is looked up by its URL); the level and passing percentage; answers on the site
  that disagree with the repository's `.bestpractices.json`; justification
  URLs on the site that point at files no longer on `main`; and a level lost
  (the site's `lost_<level>_at` after its `achieved_<level>_at`). Exit 1 on
  any of those (drift), 2 when a project cannot be read, else 0. With
  --issues, each repository keeps one issue `[bestpractices] N finding(s)`:
  opened on drift, updated in place when the findings change, closed when
  clean. The issue token comes from BESTPRACTICES_TOKEN (the org bot's);
  without it, or with --dry-run, nothing is written. GitHub reads go through
  `gh api` with GH_TOKEN. Requests to the site are one a second at most, as
  its API documentation asks; nothing is ever POSTed to it.

Stdlib only; Python 3.11+ (tomllib).
"""

