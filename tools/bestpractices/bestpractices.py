def load_answers(path):
    """{criterion: (status, justification)} from a .bestpractices.json, passing criteria only."""
    try:
        with open(path) as fh:
            data = json.load(fh)
    except (OSError, ValueError) as e:
        raise Failure(f"bestpractices: {path}: {e}") from None
    return {
        c: (data[f"{c}_status"], data.get(f"{c}_justification", ""))
        for c in PASSING
        if f"{c}_status" in data
    }


def proposal_urls(project, ans, section="passing", limit=PROPOSAL_LIMIT):
    """The site's automation-proposal links for an existing project
    (/en/projects/<id>/<section>/edit?<criterion>_status=..&<criterion>_justification=..):
    every answered criterion except the owner-only ones, split into links under `limit`
    characters, never splitting one criterion's pair. Opening one changes nothing: the
    logged-in maintainer reviews the proposed answers and saves."""
    base = f"{SITE}/en/projects/{project}/{section}/edit?"
    urls, cur = [], []
    for c, (status, why) in ans.items():
        if status in ("?", "unknown") or c in OWNER_ONLY:
            continue
        pair = [(f"{c}_status", status)] + ([(f"{c}_justification", why)] if why else [])
        part = urllib.parse.urlencode(pair, quote_via=urllib.parse.quote)
        if len(base) + len(part) > limit:
            raise Failure(f"bestpractices: {c}: its answer alone is over {limit} characters")
        if cur and len(base) + len("&".join(cur + [part])) > limit:
            urls.append(base + "&".join(cur))
            cur = []
        cur.append(part)
    if cur:
        urls.append(base + "&".join(cur))
    return urls


def register(slug, repo_dir, today, remote, answers_file=None):
    """Registered: the id, the org-sync line and the proposal links. Not registered: where
    to register (the site has no pre-filled registration form: /en/projects?as=edit needs an
    existing project), and that this command then gives the proposal links."""
    pid = registered(remote, slug)
    if not pid:
        print(f"{slug} is not registered on bestpractices.dev.")
        print(f"1. Logged in, add it at {SITE}/en/projects/new with https://github.com/{slug}")
        print("2. Run this command again: it prints the proposal links for the new project.")
        return 0
    print(f"{slug} is registered: {SITE}/projects/{pid}")
    print(f'add to {CONFIG}: bestpractices_project = "{pid}" (if it is not there yet)')
    repo_dir = repo_dir or os.path.join("..", slug.split("/")[1])
    if answers_file:
        ans = load_answers(answers_file)
    elif os.path.isfile(os.path.join(repo_dir, OUT)):
        ans = load_answers(os.path.join(repo_dir, OUT))
    elif os.path.isdir(repo_dir):
        ans = answers(repo_dir, slug, today)
    else:
        print(
            f"bestpractices: no checkout at {repo_dir}: pass --dir for the proposal links",
            file=sys.stderr,
        )
        return 0
    urls = proposal_urls(pid, ans)
    print(
        f"Proposal links (open each logged in, review, Save; owner-only criteria left out): {len(urls)}"
    )
    for i, u in enumerate(urls, 1):
        print(f"{i}. {u}")
    longest = max(map(len, urls), default=0)
    print(
        f"bestpractices: {summary(ans)}; {len(urls)} link(s), longest {longest} characters",
        file=sys.stderr,
    )
    return 0


