# --- reading a repository -----------------------------------------------------


def read(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def load_config(repo_dir):
    text = read(os.path.join(repo_dir, CONFIG))
    if text is None:
        return {}
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise Failure(f"bestpractices: {CONFIG}: {e}") from None


def git_slug(repo_dir):
    r = subprocess.run(
        ["git", "-C", repo_dir, "remote", "get-url", "origin"], capture_output=True, text=True
    )
    m = re.search(r"github\.com[:/]([^/]+/[^/]+?)(\.git)?/?$", r.stdout.strip())
    return m.group(1) if r.returncode == 0 and m else None


def last_commit(repo_dir):
    r = subprocess.run(
        ["git", "-C", repo_dir, "log", "-1", "--format=%cs"], capture_output=True, text=True
    )
    return r.stdout.strip() if r.returncode == 0 and r.stdout.strip() else None


def files_of(repo_dir):
    """Every file under repo_dir, relative, without .git."""
    out = []
    for root, dirs, files in os.walk(repo_dir):
        dirs[:] = sorted(d for d in dirs if d not in (".git", "node_modules"))
        out += [os.path.relpath(os.path.join(root, f), repo_dir) for f in sorted(files)]
    return out


class Repo:
    """What the answers are derived from: the files of one checkout."""

    def __init__(self, repo_dir, slug):
        self.dir, self.slug = repo_dir, slug
        self.owner = slug.split("/")[0]
        self.base = f"https://github.com/{slug}"
        self.files = set(files_of(repo_dir))
        self.cfg = load_config(repo_dir)
        # the CI workflows first, so evidence names ci.yml before a manual one
        wf = sorted(
            (f for f in self.files if re.match(r"\.github/workflows/[^/]+\.ya?ml$", f)),
            key=lambda f: (not os.path.basename(f).startswith("ci"), f),
        )
        self.workflows = {f: read(os.path.join(repo_dir, f)) or "" for f in wf}

    def has(self, *paths):
        return next((p for p in paths if p in self.files), None)

    def text(self, path):
        return read(os.path.join(self.dir, path)) or "" if path else ""

    def url(self, path):
        kind = "tree" if path.endswith("/") else "blob"
        return f"{self.base}/{kind}/main/{path.rstrip('/')}"

    def org_file(self, name):
        """The org default (GitHub shows it in every repository without its own)."""
        if self.owner == ORG:
            return f"https://github.com/{ORG}/.github/blob/main/{name}"
        return None

    def workflow(self, pattern):
        """The first workflow whose text matches, as a URL, else None."""
        rx = re.compile(pattern, re.I | re.M)
        return next((self.url(f) for f, t in self.workflows.items() if rx.search(t)), None)

    def grep(self, pattern, suffixes):
        rx = re.compile(pattern, re.I | re.M)
        for f in sorted(self.files):
            if f.endswith(suffixes) and rx.search(self.text(f)):
                return f
        return None


