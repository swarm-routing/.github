def _urlopen(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.read().decode("utf-8")
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise Failure(f"Crossref answered HTTP {e.code}") from None
    except (urllib.error.URLError, OSError, UnicodeDecodeError) as e:
        raise Failure(f"Crossref unreachable: {getattr(e, 'reason', type(e).__name__)}") from None


def crossref(url):
    """Crossref's JSON message at url; None for a 404. One retry on any other failure."""
    fetch = FETCH or _urlopen
    for attempt in (1, 2):
        try:
            text = fetch(url)
            break
        except Failure:
            if attempt == 2:
                raise
            if FETCH is None:
                time.sleep(2)
    if text is None:
        return None
    try:
        msg = json.loads(text)["message"]
    except (ValueError, KeyError, TypeError):
        raise Failure("Crossref sent a response that is not a works record") from None
    if not isinstance(msg, dict):
        raise Failure("Crossref sent a response that is not a works record")
    return msg


def _clean(value, field):
    s = html.unescape(re.sub(r"<[^>]+>", "", str(value)))
    s = re.sub(r"\s+", " ", s.replace("{", "").replace("}", "")).strip()
    if field in TEXT_FIELDS:
        s = re.sub(r"(?<!\\)([&%#$])", r"\\\1", s)
    return s


def cited_keys(text):
    return set(CITE.findall(text)) | {m.group(1) for m in CITE_LOC.finditer(text)}


def crossref_entry(msg, key, role):
    """A references.bib entry from a Crossref works message; fields Crossref lacks stay out."""
    ctype = msg.get("type", "")
    kind = CROSSREF_TYPES.get(ctype, "misc")
    degree = " ".join(msg.get("degree") or []).lower()
    if kind == "phdthesis" and re.search(r"master|\bm\.?sc?\b|\bm\.?a\b", degree):
        kind = "mastersthesis"
    f = {}
    names = []
    for a in msg.get("author") or []:
        if not isinstance(a, dict):
            continue
        if a.get("family"):
            given = _clean(a.get("given", ""), "author")
            names.append(_clean(a["family"], "author") + (f", {given}" if given else ""))
        elif a.get("name"):
            names.append("{" + _clean(a["name"], "author") + "}")
    if names:
        f["author"] = " and ".join(names)
    title = (msg.get("title") or [""])[0]
    sub = (msg.get("subtitle") or [""])[0]
    if title:
        f["title"] = _clean(title + (f": {sub}" if sub else ""), "title")
    containers = [c for c in msg.get("container-title") or [] if c]
    if containers:
        if kind == "article":
            f["journal"] = _clean(containers[0], "journal")
        elif kind in ("inproceedings", "incollection"):
            f["booktitle"] = _clean(containers[-1], "booktitle")
            if len(containers) > 1:
                f["series"] = _clean(containers[0], "series")
        elif kind == "book":
            f["series"] = _clean(containers[0], "series")
    for src, dst in (("volume", "volume"), ("issue", "number")):
        if msg.get(src):
            f[dst] = _clean(msg[src], dst)
    if msg.get("page"):
        f["pages"] = re.sub(r"[-–]+", "--", _clean(msg["page"], "pages").replace(" ", ""))
    inst = [i.get("name") for i in msg.get("institution") or [] if i.get("name")]
    if kind in ("phdthesis", "mastersthesis"):
        if inst or msg.get("publisher"):
            f["school"] = _clean(inst[0] if inst else msg["publisher"], "school")
    elif kind == "techreport":
        if inst or msg.get("publisher"):
            f["institution"] = _clean(inst[0] if inst else msg["publisher"], "institution")
    elif msg.get("publisher"):
        f["publisher"] = _clean(msg["publisher"], "publisher")
    parts = ((msg.get("issued") or {}).get("date-parts") or [[None]])[0]
    if parts and parts[0]:
        f["year"] = str(parts[0])
    f["doi"] = _clean(msg.get("DOI", ""), "doi")
    f["keywords"] = role
    return {"key": key, "type": kind, "fields": f}


def bib_entry(doi, key, role):
    """(exit code, text): the entry, or the reason there is none."""
    doi = bib.norm_doi(doi)
    if not re.fullmatch(r"10\.\d{4,9}/\S+", doi):
        return 1, f"bib entry: {doi!r} is not a DOI (10.NNNN/...)"
    if not SHEET_KEY.fullmatch(key):
        return (
            2,
            f"bib entry: {key!r} is not a key a sheet can cite (a letter, then letters, digits, _ or -)",
        )
    try:
        msg = crossref(f"{CROSSREF}/{urllib.parse.quote(doi, safe='/')}")
    except Failure as e:
        return 2, f"bib entry: {e}"
    if msg is None:
        why = f"bib entry: Crossref has no record of {doi}"
        if doi.startswith("10.5281/"):
            why += " (a Zenodo DOI is DataCite's: for an org release use zenodo.py bibtex)"
        return 1, why + "; nothing written (an entry is never guessed)"
    try:
        entry = crossref_entry(msg, key, role)
    except (AttributeError, TypeError, KeyError, IndexError):
        return 2, f"bib entry: Crossref's record of {doi} is not in the works shape"
    return 0, bib.format_entry(entry).rstrip("\n")


def sources_table(entries):
    rows = ["| Key | Citation | Link |", "|---|---|---|"]
    for e in sorted(entries, key=lambda e: e["key"].lower()):
        link = bib.doi_link(e)
        cells = [e["key"], bib.citation(e), f"<{link}>" if link else "—"]
        rows.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
    return "\n".join(rows)


def _between(text):
    """(start, end) of the text between the markers, or None."""
    b = text.find(BEGIN)
    e = text.find(END, b + len(BEGIN)) if b >= 0 else -1
    if b < 0 or e < 0:
        return None
    return b + len(BEGIN), e


def render_sources(sheet, entries):
    """The sheet with its marked table rewritten; None when the markers are absent."""
    span = _between(sheet)
    if not span:
        return None
    return sheet[: span[0]] + "\n" + sources_table(entries) + "\n" + sheet[span[1] :]


MARKER_HELP = (
    f"put the two marker lines {BEGIN} and {END} under `## Sources`, around its "
    "table (or where it should go), then run `fidelity.py bib sources` again"
)


def bib_sources(repo):
    """(exit code, message)."""
    sheet_path = os.path.join(repo, SHEET)
    try:
        entries = bib.load(os.path.join(repo, BIB))
    except OSError as e:
        return 1, f"bib sources: cannot read {BIB}: {e.strerror}"
    except bib.BibError as e:
        return 1, f"bib sources: {BIB}: {e}"
    try:
        with open(sheet_path, encoding="utf-8") as fh:
            sheet = fh.read()
    except OSError:
        return 1, f"bib sources: no {SHEET}"
    new = render_sources(sheet, entries)
    if new is None:
        return 1, f"bib sources: {SHEET} has no Sources markers: {MARKER_HELP}"
    n = f"{len(entries)} entr{'y' if len(entries) == 1 else 'ies'}"
    if new == sheet:
        return 0, f"{SHEET}: Sources table up to date ({n})"
    with open(sheet_path, "w", encoding="utf-8") as fh:
        fh.write(new)
    return 0, f"{SHEET}: Sources table rewritten ({n})"


def public_files(repo):
    """Relative paths of the repository's tracked files (all files when it is not a git
    checkout), without test inputs."""
    try:
        out = subprocess.run(
            ["git", "-C", os.path.abspath(repo), "ls-files", "-z"], capture_output=True, check=True
        ).stdout.decode("utf-8", "replace")
        paths = [p for p in out.split("\0") if p]
    except (OSError, subprocess.CalledProcessError):
        paths = []
        for root, dirs, files in os.walk(repo):
            dirs[:] = sorted(d for d in dirs if not d.startswith("."))
            for name in sorted(files):
                paths.append(os.path.relpath(os.path.join(root, name), repo))
    out = []
    for p in paths:
        parts = p.replace(os.sep, "/").split("/")
        if SKIP_PARTS & set(parts[:-1]):
            continue
        ext = os.path.splitext(p)[1].lower()
        name = parts[-1]
        if ext in TEXT_EXT or ext in CODE_EXT or name in CODE_NAMES or name.startswith("README"):
            out.append(p)
    return out


def _read(repo, rel):
    try:
        with open(os.path.join(repo, rel), encoding="utf-8") as fh:
            return fh.read()
    except (OSError, UnicodeDecodeError):
        return None


def own_doi(cff):
    m = re.search(r"^doi:\s*[\"']?([^\"'\s#]+)", cff or "", re.M)
    return bib.norm_doi(m.group(1)).lower() if m else None


def _norm_title(t):
    return re.sub(r"[^a-z0-9]+", "", bib.plain(t).lower())


def crossref_doi_for(entry):
    """A DOI Crossref holds for this url-only entry's exact title, or None."""
    title = bib.plain(entry["fields"].get("title", ""))
    if not title:
        return None
    q = urllib.parse.urlencode(
        {"query.bibliographic": title, "rows": 5, "select": "DOI,title,subtitle,issued"}
    )
    msg = crossref(f"{CROSSREF}?{q}")
    year = entry["fields"].get("year", "")
    items = (msg or {}).get("items")
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, dict):
            continue
        t = (item.get("title") or [""])[0]
        sub = (item.get("subtitle") or [""])[0]
        if _norm_title(title) not in (_norm_title(t), _norm_title(f"{t} {sub}")):
            continue
        y = ((item.get("issued") or {}).get("date-parts") or [[None]])[0][0]
        if year.isdigit() and y and abs(int(year) - int(y)) > 1:
            continue
        return item.get("DOI")
    return None


def bib_check(repo, online=False):
    """(findings, warnings), each a list of lines."""
    findings, warns = [], []
    text = _read(repo, BIB)
    entries, parsed = [], False
    if text is None:
        findings.append(f"{BIB}: missing; every repository keeps one (swarm-routing/.github#307)")
    else:
        try:
            entries, parsed = bib.parse(text), True
        except bib.BibError as e:
            findings.append(f"{BIB}:{e.line}: {e.message}")
    by_key = {e["key"]: e for e in entries}
    files = {p: _read(repo, p) for p in public_files(repo)}
    files = {p: t for p, t in files.items() if t is not None}
    sheet = files.get(SHEET.replace(os.sep, "/"))
    if sheet is None:
        sheet = _read(repo, SHEET)

    # the keys the sheet cites, and every [KEY] anywhere outside the bib and the table
    if sheet is not None:
        for n, line in enumerate(sheet.splitlines(), 1):
            for key in sorted(cited_keys(line)):
                if key not in by_key and parsed:
                    findings.append(f"{SHEET}:{n}: [{key}] is cited but not in {BIB}")
    cited = set()
    for path, body in files.items():
        if path.endswith(".bib"):
            continue
        span = _between(body) if path == SHEET.replace(os.sep, "/") else None
        if span:
            body = body[: span[0]] + body[span[1] :]
        cited.update(cited_keys(body))

    cff = files.get("CITATION.cff") or _read(repo, "CITATION.cff")
    mine = own_doi(cff)
    for e in entries:
        f, where = e["fields"], f"{BIB}:{e['line']}: {e['key']}"
        doi = bib.norm_doi(f.get("doi"))
        if not doi and not f.get("url"):
            findings.append(f"{where}: neither doi nor url")
        rs = bib.roles(e)
        bad = [r for r in rs if r not in bib.ROLES]
        if bad:
            findings.append(
                f"{where}: keywords {', '.join(bad)} not a role ({', '.join(bib.ROLES)})"
            )
        if not rs and e["key"] not in cited:
            findings.append(f"{where}: no file cites [{e['key']}] and it has no role (keywords)")
        if mine and doi.lower() == mine:
            findings.append(
                f"{where}: the repository's own DOI {doi} (CITATION.cff doi); "
                "a repository never lists itself"
            )
        if not doi and f.get("url"):
            m = DOI_IN.search(f["url"])
            if m:
                warns.append(
                    f"{where}: its url names DOI {m.group(0)}: give it doi = {{{m.group(0)}}}"
                )
            elif online:
                try:
                    found = crossref_doi_for(e)
                except (Failure, AttributeError, TypeError, IndexError) as x:
                    warns.append(f"{where}: no usable Crossref answer: {x}")
                    found = None
                if found:
                    warns.append(f"{where}: Crossref has DOI {found} for this title: give it doi")

    # rendered references: a DOI shown through any host but doi.org
    rendered = [
        p
        for p in files
        if p in ("README.md", "CITATION.cff") or (p.startswith("docs/") and p.endswith(".md"))
    ]
    dois = {bib.norm_doi(e["fields"].get("doi")).lower(): e["key"] for e in entries}
    dois.pop("", None)
    for path in sorted(rendered):
        for n, line in enumerate(files[path].splitlines(), 1):
            for m in DOI_IN.finditer(line):
                d = m.group(0).rstrip(".,;").lower()
                if d not in dois:
                    continue
                before = line[: m.start()]
                if before.endswith("/") and not re.search(r"(?i)https://doi\.org/$", before):
                    link = before.split()[-1] if before.split() else before
                    findings.append(
                        f"{path}:{n}: [{dois[d]}] shown as {link}{m.group(0)}, "
                        f"not https://doi.org/{m.group(0)}"
                    )
    if sheet is not None and parsed:
        if _between(sheet) is None:
            findings.append(f"{SHEET}: no Sources markers: {MARKER_HELP}")
        elif render_sources(sheet, entries) != sheet:
            findings.append(
                f"{SHEET}: the Sources table is not the one {BIB} gives: run `fidelity.py bib sources`"
            )

    # the private paper library (the bib's own header may state the rule)
    for path in sorted(files):
        body = files[path]
        skip = 0
        if path == BIB.replace(os.sep, "/"):
            head = bib.header(body)
            if re.search(r"\bnever\b", head, re.I):
                skip = head.count("\n")
        ext = os.path.splitext(path)[1].lower()
        code = ext in CODE_EXT or os.path.basename(path) in CODE_NAMES
        # blank what is not public prose (code, the rule in the bib's header), keep line numbers
        lines = [
            "" if n <= skip or (code and not COMMENT.match(line)) else line
            for n, line in enumerate(body.split("\n"), 1)
        ]
        text_ = "\n".join(lines)
        seen = set()
        for m in PRIVATE.finditer(text_):
            n = text_.count("\n", 0, m.start()) + 1
            if n in seen:
                continue
            seen.add(n)
            phrase = re.sub(r"\s+", " ", m.group(0))
            findings.append(
                f"{path}:{n}: names the private paper library ({phrase!r}): "
                "cite the work by its DOI link instead"
            )
    return findings, warns


