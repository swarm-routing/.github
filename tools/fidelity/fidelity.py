def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--self-test", action="store_true")
    sub = p.add_subparsers(dest="cmd")
    s = sub.add_parser("skeleton")
    s.add_argument("--protocol", required=True)
    s.add_argument("--key", default="P1")
    s.add_argument("--citation", default="TODO: authors, title, venue, year, DOI")
    c = sub.add_parser("check")
    c.add_argument("file")
    r = sub.add_parser("row")
    r.add_argument("file")
    r.add_argument("--protocol", default="")
    v = sub.add_parser("verify")
    v.add_argument("file")
    v.add_argument("--text", action="append", required=True, metavar="KEY=PATH")
    b = sub.add_parser("bib", help="docs/references.bib: check, entry, sources")
    bsub = b.add_subparsers(dest="bibcmd", required=True)
    bc = bsub.add_parser("check")
    bc.add_argument("repo")
    bc.add_argument("--online", action="store_true")
    be = bsub.add_parser("entry")
    be.add_argument("doi")
    be.add_argument("--key", required=True)
    be.add_argument("--role", required=True, choices=bib.ROLES)
    bs = bsub.add_parser("sources")
    bs.add_argument("repo")
    args = p.parse_args(argv)
    if args.self_test:
        return self_test()
    if args.cmd == "bib":
        if args.bibcmd == "entry":
            code, out = bib_entry(args.doi, args.key, args.role)
            print(out, file=sys.stdout if code == 0 else sys.stderr)
            return code
        if args.bibcmd == "sources":
            code, out = bib_sources(args.repo)
            print(out, file=sys.stdout if code == 0 else sys.stderr)
            return code
        if not os.path.isdir(args.repo):
            print(f"bib check: {args.repo} is not a directory", file=sys.stderr)
            return 2
        findings, warns = bib_check(args.repo, args.online)
        for f in findings:
            print(f)
        for w in warns:
            print(f"WARN {w}")
        print(f"fidelity bib check: {'ok' if not findings else f'{len(findings)} finding(s)'}")
        return 1 if findings else 0
    if args.cmd == "verify":
        texts = {}
        try:
            for kv in args.text:
                key, _, path = kv.partition("=")
                if not key or not path:
                    print(f"fidelity verify: --text {kv!r} is not KEY=PATH (e.g. R05=thesis.txt)")
                    return 2
                with open(path, encoding="utf-8", errors="replace") as fh:
                    texts[key] = fh.read()
            with open(args.file, encoding="utf-8") as fh:
                errors, warns, checked = verify_text(fh.read(), texts)
        except (OSError, Failure) as e:
            print(f"fidelity verify: {e}")
            return 2
        for e in errors:
            print(f"FAIL {e}")
        for w in warns:
            print(f"WARN {w}")
        print(
            f"fidelity verify: {checked} locator(s) checked; "
            f"{len(errors)} miss(es), {len(warns)} warning(s)"
        )
        if not checked:
            print("fidelity verify: nothing was checked: no locator of a key given with --text")
        return 1 if errors or not checked else 0
    if args.cmd == "skeleton":
        sys.stdout.write(skeleton(args.protocol, args.key, args.citation))
        return 0
    if args.cmd in ("check", "row"):
        with open(args.file, encoding="utf-8") as fh:
            text = fh.read()
        bib_keys, bib_problem = (), None
        bib_path = os.path.join(os.path.dirname(os.path.abspath(args.file)), "references.bib")
        if os.path.exists(bib_path):
            try:
                bib_keys = [e["key"] for e in bib.load(bib_path)]
            except bib.BibError as e:
                bib_problem = f"references.bib: {e}"
        problems, summary = check_text(text, bib_keys)
        if bib_problem:
            problems.insert(0, bib_problem)
        if args.cmd == "check":
            for prob in problems:
                print(f"{args.file}: {prob}")
            if summary:
                m, q = summary["counts"]["Mechanisms"], summary["counts"]["Parameters"]
                print(
                    f"{args.file}: {sum(m.values())} mechanisms, {sum(q.values())} parameters; "
                    f"unknown: {', '.join(summary['unknowns']) or 'none'}; "
                    f"repo choice: {', '.join(summary['choices']) or 'none'}; "
                    f"open (sourced, status unknown): {', '.join(summary['open']) or 'none'}"
                )
            print(f"fidelity check: {'ok' if not problems else f'{len(problems)} problem(s)'}")
            return 1 if problems else 0
        if problems:
            for prob in problems:
                print(f"{args.file}: {prob}", file=sys.stderr)
            return 1
        name = args.protocol or protocol_name(text, os.path.dirname(os.path.abspath(args.file)))
        print(row_line(summary, name))
        return 0
    p.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
